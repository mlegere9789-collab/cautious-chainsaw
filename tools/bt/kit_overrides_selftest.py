    out = KO.compile_lines(ctx, 'ta', [line('ta:0001', 'cs-1c-mclaws-kershaw-2sc', 'arms', arms('p1853_enfield'), kit_field='weapon', basis='regimental_history', source='NY-GB-1900', part=None, report_id='NY1-S001', printed_page=None)], {})
