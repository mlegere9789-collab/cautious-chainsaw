    ok('ops: a guard that no longer holds is reported stale and nothing changes', len(st) == 1 and T['artillery']['batteries']['X']['guns'] == [2] and 'changed since' in st[0], st)
    KO.apply_op(T, {'id': 'o3', 'op': 'set', 'table': 'artillery', 'path': ['batteries', 'X', 'tier'], 'value': 'documented', 'before_absent': True}, st)
    ok('ops: before_absent on an existing key is stale', len(st) == 2)
    KO.apply_op(T, {'id': 'o4', 'op': 'create', 'table': 'artillery', 'path': ['batteries'], 'key': 'Y', 'value': {'a': 1}}, st)
    KO.apply_op(T, {'id': 'o5', 'op': 'create', 'table': 'artillery', 'path': ['batteries'], 'key': 'Y', 'value': {'a': 2}}, st)
    ok('ops: create adds a record and refuses to overwrite one', T['artillery']['batteries']['Y'] == {'a': 1} and len(st) == 3)
    KO.apply_op(T, {'id': 'o6', 'op': 'append', 'table': 'artillery', 'path': ['batteries', 'X', 'l'], 'value': 1, 'unique': True}, st)
    KO.apply_op(T, {'id': 'o7', 'op': 'append', 'table': 'artillery', 'path': ['batteries', 'X', 'l'], 'value': 5, 'unique': True}, st)
    ok('ops: append with unique adds only what is new', T['artillery']['batteries']['X']['l'] == [1, 5])
    KO.apply_op(T, {'id': 'o8', 'op': 'register_source', 'table': 'artillery', 'key': 'S', 'value': {'weak': False}}, st)
    KO.apply_op(T, {'id': 'o9', 'op': 'register_source', 'table': 'artillery', 'key': 'S', 'value': {'weak': True}}, st)
    ok('ops: a source is registered once; a different record under the same key is stale', 'S' in T['artillery']['sources'] and len(st) == 4)
    try:
        KO.apply_op(T, {'id': 'o10', 'op': 'set', 'table': 'artillery', 'path': ['batteries', 'X', 'guns'], 'value': 1}, [])
        raised = False
    except KO.OverrideError:
        raised = True
    ok('ops: a set without any guard is refused', raised)

    # ---- guns: fills a gap -------------------------------------------------------------------------------------
