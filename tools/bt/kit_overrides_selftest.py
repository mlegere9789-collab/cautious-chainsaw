    out = KO.compile_lines(ctx, 'tg', [line('tg:0001', 'us-1c-art-5me', 'guns', guns_val(6), as_of='1863-07-01'), line('tg:0002', 'us-1c-art-5me', 'guns', guns_val(5, printed='five 12-pounders'), as_of='1863-07-03')], {})
