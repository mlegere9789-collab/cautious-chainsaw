    out = KO.compile_lines(ctx, 'tg', [line('tg:0001', 'us-1c-art-5me', 'guns', guns_val())], {})
    ops = {tuple(o['path']): o for o in out.ops if o.get('path')}
    ok('guns: evidence for a battery whose card has a gap sets guns, status, tier and sources', ops[('batteries', 'US.ART.5th_Maine_E', 'guns')]['value'][0]['count'] == 6 and ops[('batteries', 'US.ART.5th_Maine_E', 'tier')]['value'] == 'documented'
       and ops[('batteries', 'US.ART.5th_Maine_E', 'source_keys')]['value'] == ['OR27-1'] and card0['guns'] == [], [o.get('path') for o in out.ops])
    ok('guns: the value replaced is kept (guns_replaced) and every operation cites its evidence line', ops[('batteries', 'US.ART.5th_Maine_E', 'guns_replaced')]['value']['guns_status'] == 'gap' and all(o['evidence_ids'] or o['op'] == 'register_source' for o in out.ops))
