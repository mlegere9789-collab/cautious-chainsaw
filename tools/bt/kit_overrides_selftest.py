TMP = os.path.join(K.ROOT, 'tmp', 'kit-plan', 'selftest')
BANNED = re.compile(r'\b(claude|anthropic|agents?|subagents?|generated by|built by|do not edit|hand-edit|automated)\b', re.I)


def line(i, unit, field, value, tier='documented', basis='report_text', kit_field=None, as_of='1863-07-01', source='OR27-1', **kw):
    o = {'type': 'evidence', 'id': i, 'unit_id': unit, 'field': field, 'value': value, 'basis': basis, 'tier': tier, 'as_of': as_of, 'source_id': source, 'part': 1, 'report_id': 'OR27-1-R028', 'printed_page': 231,
         'offset': 761301, 'quote': "Stevens' battery (Fifth Maine, six 12-pounders) was posted", 'quote_mode': 'exact'}
    if kit_field:
        o['kit_field'] = kit_field
    o.update(kw)
    return o


def guns_val(n=6, tid='napoleon_12pdr_m1857', state='present', printed='six 12-pounders'):
    return {'pieces': [{'printed': printed, 'count': n, 'type_id': tid}], 'total': n, 'state': state, 'scope': 'battery'}


def write_ov(d, group, out, name=None):
    os.makedirs(d, exist_ok=True)
    doc = {'schema': KO.SCHEMA, 'group': group, 'ops': out.ops, 'unapplied': out.unapplied}
    with open(os.path.join(d, (name or group) + '.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
    return doc


def fresh(name):
    d = os.path.join(TMP, name)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    return d


def data_checks_of(tables, name):
    import check_kit as CK
    d = fresh(name + '_kit')
    for t, obj in tables.items():
        with open(os.path.join(d, KO.FILES[t]), 'w', encoding='utf-8', newline='\n') as f:
            json.dump(obj, f, indent=1, ensure_ascii=False)
    kit = CK.Kit(d)
    errs, warns, info = CK.data_checks(kit)
    return kit, errs, CK


def apply_to(base, ov_dir):
    ks, w, a, c, rep = KO.apply_overrides(base['kit_specs'], base['weapons'], base['artillery'], base['cavalry'], ov_dir)
    return {'kit_specs': ks, 'weapons': w, 'artillery': a, 'cavalry': c}, rep


def run(ok):
    base = KO.load_base()
    gdoc = K.groups_doc()
