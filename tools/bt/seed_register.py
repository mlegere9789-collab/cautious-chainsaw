"""Phase-0 governance seed part 2: requirements.json (+sub-requirements), Evidence-Gap Register entries, Decision Log,
library status, phase budget, hardware profile. Run after seed_governance.py. Idempotent.
Content tables live in seed_register_data.py so this file stays the generator."""
import json, os, re
from seed_register_data import EG_STATIC, OWNER, LIB, PHASES, DEC_CONFLICTS, DEC_D8, HARDWARE
from seed_register_visual import EG_VISUAL, LIB_EXTRA  # FIGURES / ANIMATION / FX / AUDIO gaps + later library rows

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
G = os.path.join(ROOT, 'docs', 'battle-theatre', 'GOVERNANCE')
REG = os.path.join(G, 'register'); os.makedirs(REG, exist_ok=True)
os.makedirs(os.path.join(G, 'budget'), exist_ok=True); os.makedirs(os.path.join(G, 'library'), exist_ok=True)
J = lambda p: json.load(open(os.path.join(G, p), encoding='utf-8'))
src = J('_req_src.json'); reqs = src['requirements']; trace = src['trace_gates']
rows = [json.loads(l) for l in open(os.path.join(G, 'timeline_seed.jsonl'), encoding='utf-8')]
L = open(os.path.join(ROOT, 'docs', 'battle-theatre', 'BIBLE', 'plan-clean.txt'), encoding='utf-8').read().split('\n')
text = '\n'.join(L)
sids = sorted(set(re.findall(r'\bS-0\d\d\b', text)))
eids = sorted(set(re.findall(r'\bE-\d\d\b', text)))
pids = sorted(set(re.findall(r'\bP-\d\d\b', text)))
gids = sorted(set(re.findall(r'\bG-\d\d\b', text)))
conf = J('conflict_register.json')

# ---------- requirements.json ----------
subs = []
def add(rid, sid, txt, gates=None, origin='pdf', reg=None):
    subs.append({'id': sid, 'requirement_id': rid, 'text': txt, 'source_status': 'seeded_unverified', 'origin': origin,
                 'register_ids': reg or [], 'gate_ids': trace.get(rid, []) if gates is None else gates,
                 'passes': False, 'owner_decision_ids': []})
for i, r in enumerate(rows, 1):
    add('R11', f'R11.{i:04d}', f'Timeline row {r["id"]} (tier {r["tier"]}) has a visual realization or an open register entry.', ['Q17', 'Q12'],
        reg=['EG-TL-' + r['id']] if r['tier'] == 'open gap' else None)
epi = [json.loads(l) for l in open(os.path.join(G, 'epilogue_seed.jsonl'), encoding='utf-8')]
for i, r in enumerate(epi, 1):
    add('R22', f'R22.{i:04d}', f'Epilogue row {r["id"]} (PDF tier {r["tier"]}; sources are encyclopedia/blog leads, so verify before use) is realized or registered.', ['Q28', 'Q17'])
for x in sids: add('R14', f'R14.{x}', f'State-schedule entry {x} changes state at its documented window.', ['Q07', 'Q09'])
for x in eids: add('R14', f'R14.{x}', f'Construction chronology entry {x} is built on screen, never pre-placed.', ['Q08'])
for x in pids: add('R13', f'R13.{x}', f'Pre-existing feature {x} is present at frame one, never animated as construction.', ['Q03'])
for x in gids: add('R13', f'R13.{x}', f'Gun emplacement {x} carries gun type/count and prepared-vs-improvised state.', ['Q14'])
for n in range(1, 46): add('R12', f'R12.{n:03d}', f'Terrain source catalog item #{n} has a status and is used or registered.', ['Q25', 'Q16'])
for c in conf: add('R03', f'R03.{c["id"]}', f'Conflict {c["id"]} ({c["topic"]}) carries every value as a selectable scenario; default is an owner decision.', ['Q02', 'Q19'], reg=[])
for rid in reqs: add(rid, f'{rid}.0000', 'Top-level acceptance: all child sub-requirements pass or link to an open register entry with active reconstruction.')
for oid, t in OWNER: add('OWNER', f'{oid}.0000', t, [], origin='owner_chat')
json.dump({'_doc': 'Machine-readable copy of PDF Section A. NEVER edit requirement wording (only the owner may). Only passes and links may change. Owner chat additions are origin=owner_chat and are kept apart from PDF text. Generated by tools/bt/seed_register.py.',
           'requirements': {k: {'text': v, 'gate_ids': trace.get(k, [])} for k, v in reqs.items()}, 'sub_requirements': subs},
          open(os.path.join(G, 'requirements.json'), 'w', encoding='utf-8'), indent=1, ensure_ascii=False)

# ---------- Evidence-Gap Register ----------
EG = [dict(e) for e in EG_STATIC]
oq = ' '.join(J('_open_questions.json')); pos = 0; qs = []
for n in range(1, 43):
    m = re.search(r'(?<!\d)%d\. (?=[A-Z])' % n, oq[pos:])
    if m: qs.append((n, pos + m.start())); pos += m.end()
for k, (n, st) in enumerate(qs):
    en = qs[k + 1][1] if k + 1 < len(qs) else len(oq)
    EG.append(dict(title=f'PDF Appendix C.3 open question {n}', rids=['R21'], cat='evidence missing', desc=oq[st:en].strip()[:600], why='Open per PDF.',
                   searched='PDF Appendix C.3', subst='Phase 1 audit', recon='See question text', tier='inferred', competing='-', marking='Register link', impact='varies', owner_q='', rec='', status='open'))
for r in [r for r in rows if r['tier'] == 'open gap']:
    EG.append(dict(id='EG-TL-' + r['id'], title='Timeline open gap ' + r['id'], rids=['R11'], cat='evidence missing', desc=r['text_raw'][:500], why='Row tagged open gap by PDF.',
                   searched='PDF B.2', subst='None (gap rows generate no behaviour)', recon='Map marker in evidence layer', tier='inferred', competing='-', marking='Evidence-layer marker', impact=r['id'], owner_q='', rec='', status='open'))
EG += [dict(e) for e in EG_VISUAL]
# Safety net: a hand-written register file whose id is not in the seed data is adopted (parsed back into a row), never deleted.
_K = {'ID': 'id', 'Requirement IDs': 'rids', 'Category': 'cat', 'Description': 'desc', 'Why literal 100% is not possible or blocked': 'why',
      'Evidence searched': 'searched', 'Autonomous substitute applied': 'subst', 'Strongest evidence-based reconstruction': 'recon', 'Confidence tier': 'tier',
      'Competing values': 'competing', 'Product marking': 'marking', 'Visual and audio impact': 'impact', 'Review status': 'review',
      'Owner decision requested': 'owner_q', 'Agent recommendation': 'rec', 'Status': 'status'}
_have = {e['id'] for e in EG if 'id' in e}
for f in sorted(os.listdir(REG)):
    if not f.endswith('.md') or f[:-3] in _have or re.match(r'EG-\d{4}\.md$', f): continue
    t = open(os.path.join(REG, f), encoding='utf-8').read().split('\n')
    m = re.match(r'# (\S+): (.*)$', t[0]); d = {}
    for l in t:
        mm = re.match(r'^\| (.+?) \| (.*) \|$', l)
        if mm and mm.group(1) in _K: d[_K[mm.group(1)]] = mm.group(2)
    if not m or len(d) < 16: print('NOT ADOPTED (unparseable hand-written register file):', f); continue
    e = dict(id=m.group(1), title=m.group(2), rids=d['rids'].split(', '), owner_q='' if d['owner_q'] == 'none (work continues)' else d['owner_q'],
             rec='' if d['rec'] == '-' else d['rec'])
    if d['id'] != e['id']: e['id_label'] = d['id']
    if d['review'] != 'internal review only (DEC-006: no public review label)': e['review'] = d['review']
    for k in ('cat', 'desc', 'why', 'searched', 'subst', 'recon', 'tier', 'competing', 'marking', 'impact', 'status'): e[k] = d[k]
    EG.append(e); print('adopted hand-written register file', f)
n = 0
for e in EG:
    if 'id' not in e: n += 1; e['id'] = f'EG-{n:04d}'
for f in os.listdir(REG):
    if f.endswith('.md'): os.remove(os.path.join(REG, f))
for e in EG:
    body = f"""# {e['id']}: {e['title']}

| Field | Content |
|---|---|
| ID | {e.get('id_label', e['id'])} |
| Requirement IDs | {', '.join(e['rids'])} |
| Category | {e['cat']} |
| Description | {e['desc']} |
| Why literal 100% is not possible or blocked | {e['why']} |
| Evidence searched | {e['searched']} |
| Autonomous substitute applied | {e['subst']} |
| Strongest evidence-based reconstruction | {e['recon']} |
| Confidence tier | {e['tier']} |
| Competing values | {e['competing']} |
| Product marking | {e['marking']} |
| Visual and audio impact | {e['impact']} |
| Review status | {e.get('review', 'internal review only (DEC-006: no public review label)')} |
| Owner decision requested | {e['owner_q'] or 'none (work continues)'} |
| Agent recommendation | {e['rec'] or '-'} |
| Status | {e['status']} |
| Owner decision and date | (filled only from the Decision Log) |
"""
    open(os.path.join(REG, e['id'] + '.md'), 'w', encoding='utf-8').write(body)
json.dump(EG, open(os.path.join(G, 'register_index.json'), 'w', encoding='utf-8'), indent=1, ensure_ascii=False)

# ---------- Decision Log ----------
dl = ['# Decision Log (PDF Section H). Claude records; only the owner decides.\n',
      'Unanswered = OPEN; work continues on everything else (Law cl.6, Section H).\n', '## PDF vs owner-chat conflicts\n'] + DEC_CONFLICTS + ['\n## PDF D.8.2 standing decisions\n']
dl += [f'- **DEC-D8-{i:02d}** {t} **OPEN.**' for i, t in enumerate(DEC_D8, 1)]
dl.append('\n## Conflict-register defaults (PDF recommended defaults; NOT owner-decided)\n')
dl += [f'- **DEC-{c["id"]}** {c["topic"]}: {c["text"][:260]} **PENDING OWNER**' for c in conf]
# Hand-written decision entries (DEC-007 onward, DEC-FX-01, DEC-AUDIO-01, DEC-020F, DEC-ANIM-01 ...) live in decision_log_tail.md next to this script;
# any '## DEC-' block present in an existing decision_log.md but in neither the head nor the tail file is kept (appended), never dropped.
head = '\n'.join(dl) + '\n'
tail = open(os.path.join(os.path.dirname(__file__), 'decision_log_tail.md'), encoding='utf-8').read()
new = head + tail
_old = os.path.join(G, 'decision_log.md')
if os.path.exists(_old):
    _blocks = re.split(r'(?m)^(?=## )', open(_old, encoding='utf-8').read())
    _extra = [b for b in _blocks if b.startswith('## DEC-') and b.split('\n')[0] not in new]
    if _extra: print('kept', len(_extra), 'decision entries not in the seed:', [b.split('\n')[0][:30] for b in _extra]); new = new.rstrip('\n') + '\n\n' + '\n'.join(b.rstrip('\n') + '\n' for b in _extra)
open(_old, 'w', encoding='utf-8').write(new)

# ---------- manifests ----------
_lib = [dict(zip(['id', 'title', 'where', 'status', 'note'], x)) for x in LIB + LIB_EXTRA]
_lp = os.path.join(G, 'library', 'status.json')
if os.path.exists(_lp):  # keep library rows added by hand and not (yet) in the seed
    _have_l = {x['id'] for x in _lib}; _more = [x for x in json.load(open(_lp, encoding='utf-8'))['sources'] if x['id'] not in _have_l]
    if _more: print('kept', len(_more), 'library rows not in the seed:', [x['id'] for x in _more]); _lib += _more
json.dump({'_doc': 'library/status.json (PDF Section X). Statuses: scheduled, ingested, blocked, partial, print-only.', 'sources': _lib},
          open(_lp, 'w', encoding='utf-8'), indent=1)
json.dump({'_doc': 'PDF Appendix F: blank until set from the first measured vertical slice; only the owner may raise caps. Caps pace work, never remove it.',
           'phases': {p: {'unit': None, 'unit_cost': None, 'full_scope_count': None, 'retry_factor': None, 'token_cap': None, 'usd_cap': None, 'gpu_hours_cap': None, 'owner_approved': False} for p in PHASES},
           'global_guard': {k: None for k in ['per_job_turn_limit', 'per_job_spend_limit', 'concurrency_limit', 'gpu_power_temp_guard', 'no_progress_halt_sessions', 'cache_snapshot_interval']}},
          open(os.path.join(G, 'budget', 'phase_budget.json'), 'w', encoding='utf-8'), indent=1)
json.dump(HARDWARE, open(os.path.join(G, 'hardware_profile.json'), 'w', encoding='utf-8'), indent=1)
print('subreqs', len(subs), 'register entries', len(EG), 'open questions parsed', len(qs), 'S/E/P/G', len(sids), len(eids), len(pids), len(gids))
