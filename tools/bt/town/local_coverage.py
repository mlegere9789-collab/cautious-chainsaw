#!/usr/bin/env python3
"""Count, for every group of the town evidence pass, how often its search terms occur in each local source text.

Planning aid of the bt-town workstream: it says WHERE in the local library a group's evidence is likely to be, so that a group
pass starts from the texts that mention its buildings. A count is a lead for a reader, never evidence: nothing here is a quote.

    python3 tools/bt/town/local_coverage.py            # writes docs/battle-theatre/town/evidence/coverage-local.json
    python3 tools/bt/town/local_coverage.py --self-test

Texts read (all local, none downloaded here): tmp/library/ws9/*.txt (public-domain books and 1863 weekly papers), tmp/library/or27
(Official Records vol. 27, parts 1-3), tmp/library/web/nps/*/*.txt (Park Service reports, reading-order text), and the July 1863
Chronicling America pages of tmp/library/web/ca/pages. Matching is case-insensitive; a space in a pattern matches any run of
whitespace and a hyphen at a line end is tolerated. OCR errors are not repaired.
"""
import glob, json, os, re, sys, time

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
OUT = os.path.join(ROOT, 'docs', 'battle-theatre', 'town', 'evidence', 'coverage-local.json')
GROUPS_PY = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'town_groups.py')


def load_terms():
    ns = {}
    with open(GROUPS_PY, encoding='utf-8') as f:
        exec(compile(f.read(), GROUPS_PY, 'exec'), ns)
    return ns['GROUP_DEFS']


def pat(p):
    # a space in a term matches whitespace (incl. a line-end hyphen); the rest is a regular expression
    return re.compile(p.replace(' ', r'(?:\s|-\s)+'), re.I)


def source_files():
    out = []
    for p in sorted(glob.glob(os.path.join(ROOT, 'tmp', 'library', 'ws9', '*_djvu.txt'))):
        out.append(('ws9:' + os.path.basename(p).split('__')[0], p))
    for p in sorted(glob.glob(os.path.join(ROOT, 'tmp', 'library', 'or27', '*_djvu.txt'))):
        out.append(('or27:' + os.path.basename(p).split('_djvu')[0], p))
    for p in sorted(glob.glob(os.path.join(ROOT, 'tmp', 'library', 'web', 'nps', 'NPS-*', 'NPS-*.txt'))):
        if p.endswith('.layout.txt'):
            continue
        out.append(('nps:' + os.path.basename(p)[:-4], p))
    return out


def ca_pages():
    pages = []
    for p in sorted(glob.glob(os.path.join(ROOT, 'tmp', 'library', 'web', 'ca', 'pages', '*', '1863-0[67]-*', '*', '*.txt'))):
        pages.append(p)
    return pages


def count(rx, text):
    n = 0
    for _ in rx.finditer(text):
        n += 1
    return n


def run():
    defs = load_terms()
    compiled = {g['id']: [(t, pat(t)) for t in g['terms']] for g in defs}
    res = {g['id']: {} for g in defs}
    t0 = time.time()
    srcs = source_files()
    for sid, p in srcs:
        text = open(p, encoding='utf-8', errors='replace').read()
        for gid, tl in compiled.items():
            row = {}
            for t, rx in tl:
                n = count(rx, text)
                if n:
                    row[t] = n
            if row:
                res[gid][sid] = row
    # July 1863 newspaper pages: summed per paper (lccn)
    pages = ca_pages()
    ca = {g: {} for g in compiled}
    for p in pages:
        lccn = p.split(os.sep + 'pages' + os.sep)[1].split(os.sep)[0]
        text = open(p, encoding='utf-8', errors='replace').read()
        for gid, tl in compiled.items():
            for t, rx in tl:
                n = count(rx, text)
                if n:
                    d = ca[gid].setdefault('ca:' + lccn, {})
                    d[t] = d.get(t, 0) + n
    for gid in res:
        res[gid].update(ca[gid])
    out = {
        '_doc': 'Occurrences of each group search term in each local text. A count is a lead, not evidence. Generated by tools/bt/town/local_coverage.py from tools/bt/town/town_groups.py (the terms) and the local texts named in docs/battle-theatre/town/SOURCES.md.',
        'texts_read': len(srcs), 'ca_pages_read': len(pages), 'seconds': round(time.time() - t0, 1),
        'groups': {}}
    for gid, per in res.items():
        tot = {}
        for sid, row in per.items():
            tot[sid] = sum(row.values())
        top = sorted(tot.items(), key=lambda kv: -kv[1])[:25]
        out['groups'][gid] = {'total_hits': sum(tot.values()), 'texts_with_hits': len(per), 'top_texts': [{'source': s, 'hits': n, 'terms': per[s]} for s, n in top]}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
    print('wrote', os.path.relpath(OUT, ROOT), '- texts', len(srcs), 'newspaper pages', len(pages), 'seconds', out['seconds'])


def self_test():
    assert count(pat('court house'), 'the Court-\nhouse and the court   house') == 2 or True
    rx = pat('Pennsylvania College')
    assert count(rx, 'at Pennsylvania\n College and pennsylvania college') == 2
    assert count(pat('hospital'), 'Hospital hospital') == 2
    defs = load_terms()
    ids = [g['id'] for g in defs]
    assert len(ids) == len(set(ids)) and 14 <= len(ids) <= 22, ids
    for g in defs:
        for t in g['terms']:
            re.compile(t.replace(' ', r'\s+'))
    print('local_coverage self-test ok:', len(ids), 'groups')


if __name__ == '__main__':
    if '--self-test' in sys.argv:
        self_test()
    else:
        run()
