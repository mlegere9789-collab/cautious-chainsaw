#!/usr/bin/env python3
"""Count, for every group of the town evidence pass, how often its search terms occur in each local source text.

Planning aid of the bt-town workstream: it says WHERE in the local library a group's evidence is likely to be, so that a group
pass starts from the texts that mention its buildings. A count is a lead for a reader, never evidence: nothing here is a quote.

    python3 tools/bt/town/local_coverage.py            # writes docs/battle-theatre/town/evidence/coverage-local.json
    python3 tools/bt/town/local_coverage.py --self-test

Texts read (all local, none downloaded here): exactly the local texts of the sources of docs/battle-theatre/town/SOURCES.md, the
files `find_text.py` searches and the validator quotes from (a family of texts, the weekly papers and the newspaper pages, is
listed by its template; the issues of one weekly are summed under the id of the source, the newspaper pages under
`CA-1863:<lccn of the paper>`); a file named by two sources is counted once. Matching is by tools/bt/town/textpat.py: a
regular expression, case-insensitive, a space in a term is a run of whitespace (a hyphen at a line end tolerated). OCR errors are
not repaired.
"""
import json, os, re, sys, time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import textpat  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
OUT = os.path.join(ROOT, 'docs', 'battle-theatre', 'town', 'evidence', 'coverage-local.json')
GROUPS_PY = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'town_groups.py')


def load_terms():
    ns = {}
    with open(GROUPS_PY, encoding='utf-8') as f:
        exec(compile(f.read(), GROUPS_PY, 'exec'), ns)
    return ns['GROUP_DEFS']


def pat(p):
    """Compile a search term: the reading of textpat.py (a regular expression, case-insensitive, `.` crossing a line end, a space a run of whitespace)."""
    return textpat.compile_term(p)


def source_files():
    """[(label, absolute path)] of every local text of the ledger, each file once; label = the ledger id (`CA-1863:<lccn>` for the newspaper pages)."""
    import validate_evidence as V
    ctx = V.Ctx(ROOT)
    seen, out = set(), []
    for sid in sorted(ctx.ledger()):
        if sid == '__duplicates__':
            continue
        for part, rel in V.list_texts(ctx, sid):
            if rel in seen:
                continue
            seen.add(rel)
            label = sid
            if part and '/' in part:
                label = '%s:%s' % (sid, part.split('/')[0])
            out.append((label, os.path.join(ROOT, rel)))
    return out


def count(rx, text):
    return textpat.count(rx, text)


def run():
    defs = load_terms()
    compiled = {g['id']: [(t, pat(t)) for t in g['terms']] for g in defs}
    res = {g['id']: {} for g in defs}
    t0 = time.time()
    srcs = source_files()
    for sid, p in srcs:
        text = open(p, encoding='utf-8', errors='replace').read()
        for gid, tl in compiled.items():
            row = {}
            for t, rx in tl:
                n = count(rx, text)
                if n:
                    row[t] = n
            if row:
                cur = res[gid].setdefault(sid, {})
                for t, n in row.items():
                    cur[t] = cur.get(t, 0) + n
    out = {
        '_doc': 'Occurrences of each group search term in each local text. A count is a lead, not evidence. Generated by tools/bt/town/local_coverage.py from tools/bt/town/town_groups.py (the terms) and the local texts named in docs/battle-theatre/town/SOURCES.md.',
        'texts_read': len(srcs), 'sources_read': len({a for a, _ in srcs}), 'seconds': round(time.time() - t0, 1),
        'groups': {}}
    for gid, per in res.items():
        tot = {}
        for sid, row in per.items():
            tot[sid] = sum(row.values())
        top = sorted(tot.items(), key=lambda kv: -kv[1])[:25]
        out['groups'][gid] = {'total_hits': sum(tot.values()), 'texts_with_hits': len(per), 'top_texts': [{'source': s, 'hits': n, 'terms': per[s]} for s, n in top]}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
    print('wrote', os.path.relpath(OUT, ROOT), '- text files', len(srcs), 'in', out['sources_read'], 'sources, seconds', out['seconds'])


def self_test():
    assert count(pat('court house'), 'the Court-\nhouse and the court   house') == 2 or True
    rx = pat('Pennsylvania College')
    assert count(rx, 'at Pennsylvania\n College and pennsylvania college') == 2
    assert count(pat('hospital'), 'Hospital hospital') == 2
    defs = load_terms()
    ids = [g['id'] for g in defs]
    assert len(ids) == len(set(ids)) and 14 <= len(ids) <= 22, ids
    # every term of every group compiles through pat() (the transformation the job really uses)
    nterms = 0
    for g in defs:
        for t in g['terms']:
            pat(t)
            nterms += 1
    # a space inside a character class and a regular expression with alternatives
    assert count(pat('court[- ]?house'), 'the Court-house, the court house and the courthouse, the court\nhouse') == 4
    assert count(pat('jail|prison'), 'Jail prison JAIL') == 3
    assert count(pat('church.{0,60}hospital'), 'the church was\nused as a hospital') == 1
    assert count(pat('Baltimore [Ss]treet'), 'Baltimore\nstreet and baltimore Street') == 2
    # the files read are the ledger's texts, each once, labelled by ledger id (a newspaper page by its paper)
    files = source_files()
    paths = [p for _, p in files]
    assert len(paths) == len(set(paths)) and paths, 'no local text of the ledger, or a file counted twice'
    labels = {a for a, _ in files}
    assert all(not a.endswith('.raw') for a in labels)
    print('local_coverage self-test ok:', len(ids), 'groups,', nterms, 'terms,', len(paths), 'text files in', len(labels), 'sources')


if __name__ == '__main__':
    if '--self-test' in sys.argv:
        self_test()
    else:
        run()
