"""Aggregate docs/battle-theatre/library/timeline_audit_T{1,2,3}.jsonl into docs/battle-theatre/library/TIMELINE-OR27-AUDIT-OVERVIEW.md.
Pure aggregation: it adds no new claim. Every row, verdict, difference and page citation is copied from the slice files; the seed is read only for the
printed time window and the weak-source flag. Idempotent."""
import json, os, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
L = os.path.join(ROOT, 'docs', 'battle-theatre', 'library')
G = os.path.join(ROOT, 'docs', 'battle-theatre', 'GOVERNANCE')
seed = {}
for l in open(os.path.join(G, 'timeline_seed.jsonl'), encoding='utf-8'):
    r = json.loads(l)
    seed[r['id']] = r
rows = []
for s in ('T1', 'T2', 'T3'):
    for l in open(os.path.join(L, 'timeline_audit_%s.jsonl' % s), encoding='utf-8'):
        rows.append(json.loads(l))
VERDICTS = ['SUPPORTED_BY_OR', 'CONTRADICTED_BY_OR', 'AMBIGUOUS_IN_OR', 'NOT_FOUND_IN_OR', 'NOT_AN_OR_CLAIM']
cnt = collections.Counter(r['verdict'] for r in rows)
by_slice = {s: collections.Counter(r['verdict'] for r in rows if r['id'].startswith(s + '-')) for s in ('T1', 'T2', 'T3')}
out = ['# Timeline seed rows audited against the Official Records (vol. 27)', '',
       'Generated by `tools/bt/timeline_audit_overview.py` from `timeline_audit_T1/T2/T3.jsonl`. It adds no claim of its own. The seed rows, windows, tiers and defaults are untouched: '
       'every difference below is an input to an OWNER decision (Law clause 6). OR text is single-witness OCR (no second-witness diff done), and NOT_FOUND means targeted searches, not an exhaustive read.', '',
       '## Counts', '', '| Verdict | T1 | T2 | T3 | Total |', '|---|---|---|---|---|']
for v in VERDICTS:
    out.append('| %s | %d | %d | %d | %d |' % (v, by_slice['T1'][v], by_slice['T2'][v], by_slice['T3'][v], cnt[v]))
out.append('| all rows | %d | %d | %d | %d |' % (sum(by_slice['T1'].values()), sum(by_slice['T2'].values()), sum(by_slice['T3'].values()), len(rows)))
out += ['', 'Seed rows: %d; audited: %d; missing: %s.' % (len(seed), len(rows), sorted(set(seed) - {r['id'] for r in rows}) or 'none'), '']


def cite(r):
    parts = []
    for e in r.get('or_evidence', [])[:3]:
        parts.append('%s p.%s' % (e.get('report_id'), e.get('printed_page')))
    return '; '.join(parts)


def section(title, verdict):
    out.append('## %s (%d)' % (title, cnt[verdict]))
    out.append('')
    out.append('| Row | Printed window | Checked | Differs from row | OR citation |')
    out.append('|---|---|---|---|---|')
    for r in sorted((x for x in rows if x['verdict'] == verdict), key=lambda x: x['id']):
        s = seed.get(r['id'], {})
        d = (r.get('differs_from_row') or '').replace('|', '/').replace('\n', ' ')
        c = (r.get('what_was_checked') or '').replace('|', '/').replace('\n', ' ')
        out.append('| %s | %s | %s | %s | %s |' % (r['id'], (s.get('time_window_raw') or '').replace('|', '/'), c[:160], d[:260], cite(r)))
    out.append('')


section('Contradicted by the Official Records', 'CONTRADICTED_BY_OR')
section('Ambiguous inside the Official Records', 'AMBIGUOUS_IN_OR')
out.append('## Weak-source seed rows')
out.append('')
weak = [r for r in rows if seed.get(r['id'], {}).get('weak_source_flag')]
c2 = collections.Counter(r['verdict'] for r in weak)
out.append('Rows flagged weak_source in the seed: %d. By verdict: %s. SUPPORTED rows are candidates for re-tiering by the owner/integrator; this report does not change any tier.' % (len(weak), dict(c2)))
out.append('')
out.append('Supported weak-source rows: ' + ', '.join(sorted(r['id'] for r in weak if r['verdict'] == 'SUPPORTED_BY_OR')))
out.append('')
oc = sorted(r['id'] for r in rows if r.get('ocr_uncertain'))
out.append('## OCR-uncertain records (%d)' % len(oc))
out.append('')
out.append(', '.join(oc))
out.append('')
open(os.path.join(L, 'TIMELINE-OR27-AUDIT-OVERVIEW.md'), 'w', encoding='utf-8').write('\n'.join(out))
print('rows', len(rows), dict(cnt), 'weak', len(weak), dict(c2), 'ocr_uncertain', len(oc))
