import { launch } from './cdp.mjs';
import { spawn } from 'node:child_process';
const PORT = 8210;
let srv; const startSrv = (dir) => new Promise(r => { srv = spawn('node', ['serve.mjs', dir, String(PORT)], { stdio: 'ignore' }); setTimeout(r, 900); });
const stopSrv = () => new Promise(r => { try { srv.kill(); } catch {} setTimeout(r, 500); });
await startSrv('base');
const c = await launch(9420, 1440, 900, false);
const reqs = []; const exc = [];
c.ws.addEventListener('message', ev => { const m = JSON.parse(ev.data);
  if (m.method === 'Network.requestWillBeSent') reqs.push({ u: m.params.request.url, t: m.params.type });
  if (m.method === 'Runtime.exceptionThrown') exc.push((m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text).slice(0, 160));
});
await c.send('Page.addScriptToEvaluateOnNewDocument', { source: "try{localStorage.setItem('gtbg_onboarded','1')}catch(e){}" });
const snap = async (label) => ({ label, docs: reqs.filter(r => r.t === 'Document' && r.u.startsWith('http://127.0.0.1')).length, bundles: [...new Set(reqs.filter(r => /\/assets\/(index|Help|Bookmark)/.test(r.u)).map(r => r.u.split('/').pop()))], ctl: await c.ev(() => navigator.serviceWorker.controller && navigator.serviceWorker.controller.scriptURL), reg: await c.evs("navigator.serviceWorker.getRegistration().then(r=>r?{active:!!r.active,waiting:!!r.waiting,installing:!!r.installing,caches:null}:null)"), caches: await c.evs("caches.keys()"), exc: exc.slice(0, 5) });
await c.send('Page.navigate', { url: `http://127.0.0.1:${PORT}/` });
await c.sleep(11000);
console.log(JSON.stringify(await snap('1 OLD build, first visit'), null, 0));
reqs.length = 0; exc.length = 0;
await stopSrv(); await startSrv('r0_tree');
await c.send('Page.navigate', { url: `http://127.0.0.1:${PORT}/` });
await c.sleep(12000);
console.log(JSON.stringify(await snap('2 R0 deployed, returning visit (old SW active)'), null, 0));
console.log('root children:', await c.ev(() => document.getElementById('root').childElementCount), '| text:', (await c.ev(() => document.body.innerText.replace(/\s+/g,' ').slice(0, 120))));
await c.send('Input.dispatchKeyEvent', { type: 'keyDown', key: '?', code: 'Slash', windowsVirtualKeyCode: 191, text: '?' });
await c.send('Input.dispatchKeyEvent', { type: 'keyUp', key: '?', code: 'Slash', windowsVirtualKeyCode: 191 });
await c.sleep(3000);
console.log('after ? key -> chunks requested:', reqs.filter(r => /HelpModal|Bookmark/.test(r.u)).map(r => r.u.split('/').pop()), '| old entry requested again:', reqs.some(r => /index-Cg8FAMXN/.test(r.u)), '| root children:', await c.ev(() => document.getElementById('root').childElementCount), '| has help text:', await c.ev(() => /Play \/ Pause/.test(document.body.innerText)), '| exc', exc.slice(0, 3));
await stopSrv(); await c.close(); process.exit(0);
