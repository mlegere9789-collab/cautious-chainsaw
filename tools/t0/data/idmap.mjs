const NOTE_RE = new RegExp(String.raw`"notes":"((?:[^"\\]|\\.)*)"`);
export function noteOf(line) { const m = NOTE_RE.exec(line); return m ? JSON.parse('"' + m[1] + '"') : ''; }
export function remapId(file, unit, tick, note = '') {
  for (const [fk, from, to, ticks, , nre] of ALL) if (from === unit && (fk === '*' || file === fk + '.json') && (ticks === 'all' || ticks.includes(+tick)) && (!nre || nre.test(note))) return to;
  return unit;
}

