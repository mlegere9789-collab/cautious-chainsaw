// Error rates with Wilson 95% intervals from the two audit samples (docs/data-audit/sample-A.* and sample-B.*).
//   node tools/t0/data/sample-report.mjs
// Sample A: 150 claims drawn (seed 20261019) from the baseline data; b = verdict on the baseline claim, a = verdict on the same claim in the DATA build.
// Sample B: 150 claims drawn (seed 20261020) from the DATA build; v = verdict.
// Rates count I (incorrect or unsupported) over the claims that could be checked (C, I, L, R); U (unverifiable) is excluded; L (labelled) and R (removed) are not errors.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..', '..');
const rd = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const A = rd('docs/data-audit/sample-A.claims.json');
const B = rd('docs/data-audit/sample-B.claims.json');
const VA = rd('docs/data-audit/sample-A.verdicts.json').verdicts;
const VB = rd('docs/data-audit/sample-B.verdicts.json').verdicts;
const SAMPLES = ['C', 'D', 'E', 'F'].filter((x) => fs.existsSync(path.join(ROOT, `docs/data-audit/sample-${x}.verdicts.json`)));   // later samples, same format as B
function wilson(x, n) {
  if (n === 0) return [0, 1];
  const z = 1.96, p = x / n, d = 1 + (z * z) / n;
  const c = (p + (z * z) / (2 * n)) / d, h = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [Math.max(0, c - h), Math.min(1, c + h)];
}
const pc = (v) => (100 * v).toFixed(1) + '%';
function tally(rows) {
  const t = { n: 0, err: 0, C: 0, I: 0, L: 0, R: 0, U: 0 };
  for (const v of rows) { t[v]++; if (v !== 'U') { t.n++; if (v === 'I') t.err++; } }
  const [lo, hi] = wilson(t.err, t.n);
  return { ...t, rate: t.n ? t.err / t.n : 0, lo, hi };
}
const cats = [...new Set(A.claims.map((c) => c.cat))];
// baseline pool, to see which sample B claims DATA changed
const poolFile = path.join(ROOT, 'tmp', 'data-audit', 'pool-baseline.json');
fs.mkdirSync(path.dirname(poolFile), { recursive: true });
spawnSync('node', [path.join(ROOT, 'tools/t0/data/sample.mjs'), path.join(ROOT, 'baseline/dist'), '1', path.join(ROOT, 'tmp/data-audit/tmp-pool.json')], { env: { ...process.env, POOL_OUT: poolFile }, encoding: 'utf8' });
const basePool = new Map(JSON.parse(fs.readFileSync(poolFile, 'utf8')).map((c) => [c.id, c.text]));

const rowsA = A.claims.map((c, i) => ({ cat: c.cat, id: c.id, b: VA[i + 1][0], a: VA[i + 1][1] }));
const rowsB = B.claims.map((c, i) => ({ cat: c.cat, id: c.id, v: VB[i + 1][0], changed: basePool.has(c.id) ? basePool.get(c.id) !== c.text : true }));
const out = { seeds: { A: A.seed, B: B.seed }, A: {}, B: {} };
for (const x of SAMPLES) {
  const cl = rd(`docs/data-audit/sample-${x}.claims.json`), vv = rd(`docs/data-audit/sample-${x}.verdicts.json`).verdicts;
  const rows = cl.claims.map((c, i) => ({ cat: c.cat, id: c.id, v: vv[i + 1][0], changed: basePool.has(c.id) ? basePool.get(c.id) !== c.text : true }));
  out.seeds[x] = cl.seed;
  out[x] = { all: tally(rows.map((r) => r.v)), changedByData: tally(rows.filter((r) => r.changed).map((r) => r.v)), untouchedByData: tally(rows.filter((r) => !r.changed).map((r) => r.v)), byCat: Object.fromEntries(cats.map((c) => [c, tally(rows.filter((r) => r.cat === c).map((r) => r.v))])), errors: rows.filter((r) => r.v === 'I').map((r) => r.id) };
}
out.A.before = tally(rowsA.map((r) => r.b));
out.A.after = tally(rowsA.filter((r) => r.b !== 'U').map((r) => r.a));
out.B.all = tally(rowsB.map((r) => r.v));
out.B.changedByData = tally(rowsB.filter((r) => r.changed).map((r) => r.v));
out.B.untouchedByData = tally(rowsB.filter((r) => !r.changed).map((r) => r.v));
out.A.byCat = {}; out.B.byCat = {};
for (const c of cats) {
  out.A.byCat[c] = { before: tally(rowsA.filter((r) => r.cat === c).map((r) => r.b)), after: tally(rowsA.filter((r) => r.cat === c && r.b !== 'U').map((r) => r.a)) };
  out.B.byCat[c] = tally(rowsB.filter((r) => r.cat === c).map((r) => r.v));
}
// claims that were right in the baseline and wrong after (regressions), and wrong claims DATA left wrong
out.A.regressions = rowsA.filter((r) => r.b === 'C' && r.a === 'I').map((r) => r.id);
out.A.leftWrong = rowsA.filter((r) => r.b === 'I' && r.a === 'I').map((r) => r.id);
out.B.errors = rowsB.filter((r) => r.v === 'I').map((r) => r.id);
fs.writeFileSync(path.join(ROOT, 'docs/data-audit/sample-report.json'), JSON.stringify(out, null, 1));
const f = (t) => `${t.err}/${t.n} = ${pc(t.rate)} (Wilson 95% ${pc(t.lo)}-${pc(t.hi)}); C ${t.C}, I ${t.I}, L ${t.L}, R ${t.R}, U ${t.U}`;
const md = [];
md.push('# Sample results (generated by tools/t0/data/sample-report.mjs)', '');
md.push(`Sample A: 150 claims, seed ${A.seed}, drawn from the baseline data; Sample B: 150 claims, seed ${B.seed}, drawn from the DATA build.`);
md.push('Rate = incorrect or unsupported claims over claims that could be checked; unverifiable claims (U) are excluded; labelled (L) and removed (R) claims are not errors.', '');
md.push('| Measure | Result |', '|---|---|');
md.push(`| A, baseline data | ${f(out.A.before)} |`, `| A, same claims after DATA | ${f(out.A.after)} |`, `| B, DATA build (fresh claims) | ${f(out.B.all)} |`);
for (const x of SAMPLES) md.push(`| ${x}, DATA build (fresh claims, before the fixes it triggered) | ${f(out[x].all)} |`, `| ${x}, claims DATA changed | ${f(out[x].changedByData)} |`, `| ${x}, claims DATA left untouched | ${f(out[x].untouchedByData)} |`);
md.push(`| B, claims DATA changed | ${f(out.B.changedByData)} |`, `| B, claims DATA left untouched | ${f(out.B.untouchedByData)} |`, '');
md.push('| Category | A before | A after | B |'+SAMPLES.map((x) => ` ${x} |`).join(''), '|---|---|---|---|'+SAMPLES.map(() => '---|').join(''));
for (const c of cats) { const a = out.A.byCat[c], b = out.B.byCat[c]; md.push(`| ${c} | ${a.before.err}/${a.before.n} | ${a.after.err}/${a.after.n} | ${b.err}/${b.n} |`+SAMPLES.map((x) => ` ${out[x].byCat[c].err}/${out[x].byCat[c].n} |`).join('')); }
md.push('', `Regressions in A (right before, wrong after): ${out.A.regressions.length ? out.A.regressions.join(', ') : 'none'}.`, `Wrong claims DATA left wrong in A: ${out.A.leftWrong.length ? out.A.leftWrong.join(', ') : 'none'}.`, `Errors found in B: ${out.B.errors.length ? out.B.errors.join(', ') : 'none'}.`, ...SAMPLES.map((x) => `Errors found in ${x}: ${out[x].errors.length ? out[x].errors.join(', ') : 'none'}.`), '');
fs.writeFileSync(path.join(ROOT, 'docs/data-audit/sample-report.md'), md.join('\n'));
console.log(md.join('\n'));
