#!/usr/bin/env python3
"""Copy the Release 1 round 5 candidate patch groups from tools/t0/patches-next (where they are authored and tested) to tools/t0/patches (where trains.json reads them for train R1g).

    python tools/t0/r1g_sync.py            write the registered copies
    python tools/t0/r1g_sync.py --check    exit 1 when a registered copy differs from its source (the sources are the truth: edit patches-next, then sync)

Bundle groups   PERF6 (+ its "+x" parts) are copied as they are (trains.json group_order, "first": "R1g").  PERF6 anchors on the finished text of gA in the R1f entry, so no R1g bundle group may come before it and edit gA.
Page groups     PG-zperf6, PG-zseo and PG-ztail are copied with  "train": "R1g"  and without "optional" (always part of R1g); sorted names decide the order (PG-zperf5 < PG-zperf6 < PG-zseo < PG-ztail).
R1g is cumulative on R1f: nothing of R1f is changed or re-registered here (R1f stays frozen; python tools/t0/r1f_sync.py --check must still pass).
Groups handed over by the agents of the round (docs/accept/R1G-HANDOFF.md): PERF6 (Unit Roster list, tools/t0/r1g/gen_roster.py), PG-zperf6 (circle/symbol fog-without-terrain precompile variants, gen_terrain.py),
PG-ztail (/ground-remembers fog later, gen_ztail.py) and PG-zseo (the SEO round, tools/t0/seo/gen_zseo.py; its identity lines are tools/t0/seo/identity-zseo.json -> tools/t0/identity-R1g.json, see --identity).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'patches-next')
DST = os.path.join(HERE, 'patches')
BUNDLE = ['PERF6']
PAGE = ['PG-zperf6', 'PG-zseo', 'PG-ztail']
TRAIN = 'R1g'


def dumps(obj):
    return json.dumps(obj, indent=1, ensure_ascii=False) + '\n'


def identity_text():
    """tools/t0/identity-R1g.json = identity-R1d.json (the intended page identity differences of R1d..R1f) plus the lines of tools/t0/seo/identity-zseo.json."""
    base = json.load(open(os.path.join(HERE, 'identity-R1d.json'), encoding='utf-8'))
    seo = json.load(open(os.path.join(HERE, 'seo', 'identity-zseo.json'), encoding='utf-8'))
    have = {d['diff'] for d in base['differences']}
    out = dict(base)
    out['_doc'] = ('Identity differences of train R1g against the baseline (tools/t0/verify_release.mjs check V6) that are intended: identity-R1d.json plus the lines of group PG-zseo '
                   '(tools/t0/seo/identity-zseo.json). The check demands exactly this list. Generated by python tools/t0/r1g_sync.py.')
    out['differences'] = list(base['differences']) + [d for d in seo['differences'] if d['diff'] not in have]
    return dumps(out)


def wanted():
    out = {}
    for g in BUNDLE:
        for fn in sorted(os.listdir(SRC)):
            if fn == g + '.json' or (fn.startswith(g + '+') and fn.endswith('.json')):
                out[fn] = open(os.path.join(SRC, fn), encoding='utf-8', newline='').read()
    for g in PAGE:
        obj = json.load(open(os.path.join(SRC, g + '.json'), encoding='utf-8'))
        obj['group'] = g
        obj['train'] = TRAIN
        obj.pop('optional', None)
        out[g + '.json'] = dumps(obj)
    return out


def main(argv):
    check = '--check' in argv
    bad = []
    for fn, text in wanted().items():
        p = os.path.join(DST, fn)
        cur = open(p, encoding='utf-8', newline='').read() if os.path.isfile(p) else None
        if cur != text:
            bad.append(fn)
            if not check:
                open(p, 'w', encoding='utf-8', newline='').write(text)
    p = os.path.join(HERE, 'identity-R1g.json')
    text = identity_text()
    cur = open(p, encoding='utf-8', newline='').read() if os.path.isfile(p) else None
    if cur != text:
        bad.append('identity-R1g.json')
        if not check:
            open(p, 'w', encoding='utf-8', newline='').write(text)
    print(('differs: ' if check else 'written: ') + (', '.join(bad) if bad else '(nothing: already in step)'))
    return 1 if (check and bad) else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
