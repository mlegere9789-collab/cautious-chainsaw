"""Patch data files: strict loading, validation and the asserted-anchor applier (the merge_runner semantic).

A patch is (id, target, find, repl, expect[, regex]).  Before a patch is applied its `find` is counted against the CURRENT text
of the target and the count must equal `expect`; a mismatch is recorded (the patch is skipped) and the build fails at the end of
the phase with every offending patch id listed.  An overlap with an earlier patch therefore fails loudly.
"""
import os
import re

from .util import BuildError, expand_placeholders, has_placeholder, load_json, read_text, write_text

BUNDLE_TARGETS = ('js', 'help', 'book', 'css')
GROUP_KEYS = {'group', 'patches', 'delete', 'train', 'description'}
PATCH_KEYS = {'id', 'target', 'find', 'repl', 'expect', 'regex', 'note'}
REQUIRED_PATCH_KEYS = {'id', 'target', 'find', 'repl', 'expect'}
# files produced by the build itself: page/overlay data must not touch them (change the mechanism templates instead)
RESERVED_PREFIXES = ('_ops/', 'assets/')
RESERVED_FILES = ('sw.js', 'version.json')
NAME_RE = re.compile(r'^(?P<group>[A-Za-z0-9]+)(?:\+(?P<part>[A-Za-z0-9._-]+))?\.json$')
PG_RE = re.compile(r'^PG-[A-Za-z0-9._-]+\.json$')


def valid_rel_path(p):
    if not isinstance(p, str) or not p or p != p.strip():
        return False
    if p.startswith('/') or '\\' in p or ':' in p or p.endswith('/'):
        return False
    parts = p.split('/')
    return all(x not in ('', '.', '..') for x in parts)


def check_page_target(path, where):
    if not valid_rel_path(path):
        raise BuildError('%s: target %r is not a relative posix path inside dist' % (where, path))
    if path in RESERVED_FILES or any(path.startswith(x) for x in RESERVED_PREFIXES):
        raise BuildError('%s: target %r is generated by the build (use target js/help/book/css for bundle files, the '
                         'overlay for new assets, or change tools/t0/mechanism/*)' % (where, path))


def validate_patch(p, where, is_pg):
    if not isinstance(p, dict):
        raise BuildError('%s: patch must be an object' % where)
    unknown = set(p) - PATCH_KEYS
    if unknown:
        raise BuildError('%s: unknown patch keys %s' % (where, sorted(unknown)))
    missing = REQUIRED_PATCH_KEYS - set(p)
    if missing:
        raise BuildError('%s: missing patch keys %s' % (where, sorted(missing)))
    pid = p['id']
    if not isinstance(pid, str) or not pid.strip():
        raise BuildError('%s: patch id must be a non-empty string' % where)
    here = '%s [%s]' % (where, pid)
    if not isinstance(p['find'], str) or p['find'] == '':
        raise BuildError('%s: find must be a non-empty string' % here)
    if not isinstance(p['repl'], str):
        raise BuildError('%s: repl must be a string' % here)
    if isinstance(p['expect'], bool) or not isinstance(p['expect'], int) or p['expect'] < 1:
        raise BuildError('%s: expect must be an integer >= 1' % here)
    if 'regex' in p and not isinstance(p['regex'], bool):
        raise BuildError('%s: regex must be a boolean' % here)
    tgt = p['target']
    if tgt in BUNDLE_TARGETS:
        if is_pg:
            raise BuildError('%s: page groups (PG-*) cannot patch bundle files (%s); bundle patches belong to a fixed-order '
                             'group (see README "extension parts")' % (here, tgt))
        if has_placeholder(p['repl']):
            raise BuildError('%s: {{RID}}-style placeholders are not available before the release id exists; they are only '
                             'expanded in page-phase (path target) patches' % here)
    else:
        check_page_target(tgt, here)
    if p.get('regex'):
        try:
            re.compile(p['find'])
        except re.error as e:
            raise BuildError('%s: bad regex: %s' % (here, e))


def load_groups(patches_dir, cfg):
    """Read every group file.  Returns {group: {'patches': [...], 'delete': [...], 'files': [...], 'train': str|None, 'pg': bool}}.
    Files: <GROUP>.json (main) and <GROUP>+<part>.json (extension parts, appended in filename order) for the fixed-order groups
    named in trains.json, and PG-*.json page groups (one group per file)."""
    order = set(cfg['group_order']) | set(cfg.get('optional_groups', []))
    found = {}
    names = sorted(os.listdir(patches_dir))
    for fn in names:
        if not fn.endswith('.json'):
            continue
        path = os.path.join(patches_dir, fn)
        if PG_RE.match(fn):
            group, part, pg = fn[:-5], None, True
        else:
            m = NAME_RE.match(fn)
            if not m or m.group('group') not in order:
                raise BuildError('%s: file name must be <GROUP>.json / <GROUP>+<part>.json for a group in trains.json (%s) '
                                 'or PG-<name>.json' % (path, ', '.join(sorted(order))))
            group, part, pg = m.group('group'), m.group('part'), False
        data = load_json(path)
        if not isinstance(data, dict):
            raise BuildError('%s: top level must be an object' % path)
        unknown = set(data) - GROUP_KEYS
        if unknown:
            raise BuildError('%s: unknown keys %s' % (path, sorted(unknown)))
        if data.get('group') != group:
            raise BuildError('%s: "group" must be %r (it is %r)' % (path, group, data.get('group')))
        if not isinstance(data.get('patches'), list):
            raise BuildError('%s: "patches" must be a list' % path)
        if 'delete' in data and (not isinstance(data['delete'], list) or not all(valid_rel_path(x) for x in data['delete'])):
            raise BuildError('%s: "delete" must be a list of relative dist paths' % path)
        for d in data.get('delete', []):
            check_page_target(d, path + ' delete')
        train = data.get('train')
        if train is not None and (pg is False or train not in cfg['train_order']):
            raise BuildError('%s: "train" is only valid in PG-* files and must be one of %s' % (path, cfg['train_order']))
        for p in data['patches']:
            validate_patch(p, path, pg)
            p['_group'] = group
            p['_file'] = fn
        entry = found.setdefault(group, {'patches': [], 'delete': [], 'files': [], 'train': train, 'pg': pg, 'parts': []})
        if part is None:
            entry['patches'] = data['patches'] + entry['patches']     # main file first
            entry['delete'] = data.get('delete', []) + entry['delete']
        else:
            entry['patches'] += data['patches']
            entry['delete'] += data.get('delete', [])
            entry['parts'].append(fn)
        entry['files'].append(fn)
    seen = {}
    for g, e in found.items():
        for p in e['patches']:
            if p['id'] in seen:
                raise BuildError('duplicate patch id %r (%s and %s)' % (p['id'], seen[p['id']], p['_file']))
            seen[p['id']] = p['_file']
    return found


def select_groups(found, cfg, train, with_groups=()):
    """Return (bundle_groups_in_order, page_groups_sorted) active for `train`."""
    tidx = cfg['train_order'].index(train)
    tcfg = cfg['trains'][train]
    bundle = []
    order = cfg['group_order']
    for g in order:
        first = cfg['groups'][g]['first']
        if cfg['train_order'].index(first) <= tidx:
            if g not in found:
                raise BuildError('group %s is required by train %s but tools/t0/patches/%s.json is missing' % (g, train, g))
            bundle.append(g)
    for g in cfg.get('optional_groups', []):
        if g in with_groups:
            if g not in found:
                raise BuildError('optional group %s requested but tools/t0/patches/%s.json is missing' % (g, g))
            bundle.append(g)
    unknown = [g for g in with_groups if g not in cfg.get('optional_groups', [])]
    if unknown:
        raise BuildError('--with: unknown optional group(s) %s (known: %s)' % (unknown, cfg.get('optional_groups', [])))
    pages = []
    if tcfg.get('page_groups'):
        for g in sorted(k for k, v in found.items() if v['pg']):
            first = found[g]['train'] or cfg.get('pg_default_first', 'R1a')
            if cfg['train_order'].index(first) <= tidx:
                pages.append(g)
    return bundle, pages


def apply_patch(text, p, rel=None):
    """Apply one patch to `text`.  Returns (new_text, record).  The text is unchanged when the anchor count is wrong."""
    find, repl = p['find'], p['repl']
    if rel is not None:
        repl = expand_placeholders(repl, rel)
    if p.get('regex'):
        pat = re.compile(find)
        n = len(pat.findall(text))
        ok = n == p['expect']
        new = pat.sub(lambda m: m.expand(repl), text) if ok else text
    else:
        n = text.count(find)
        ok = n == p['expect']
        new = text.replace(find, repl) if ok else text
    rec = {'group': p['_group'], 'id': p['id'], 'target': p['target'], 'expect': p['expect'], 'found': n, 'ok': ok,
           'regex': bool(p.get('regex'))}
    return new, rec


def apply_bundle_phase(texts, groups, found, records):
    """Apply every bundle-target patch (js/help/book/css) in fixed group order to `texts` (dict target -> str)."""
    bad = []
    for g in groups:
        for p in found[g]['patches']:
            if p['target'] not in BUNDLE_TARGETS:
                continue
            new, rec = apply_patch(texts[p['target']], p)
            rec['phase'] = 'bundle'
            records.append(rec)
            if rec['ok']:
                texts[p['target']] = new
            else:
                bad.append(rec)
    return bad


def apply_page_phase(dist, groups, found, rel, records):
    """Apply path-target patches and deletions of the fixed-order groups (in order) and then of the PG groups.  `dist` is the
    dist root directory; `rel` the release dict used for placeholder expansion."""
    bad = []
    deleted = []
    for g in groups:
        for p in found[g]['patches']:
            if p['target'] in BUNDLE_TARGETS:
                continue
            path = os.path.join(dist, p['target'])
            rec_base = {'phase': 'page'}
            if not os.path.isfile(path):
                rec = {'group': p['_group'], 'id': p['id'], 'target': p['target'], 'expect': p['expect'], 'found': 0,
                       'ok': False, 'regex': bool(p.get('regex')), 'error': 'target file does not exist in dist'}
                rec.update(rec_base)
                records.append(rec)
                bad.append(rec)
                continue
            text = read_text(path)
            new, rec = apply_patch(text, p, rel)
            rec.update(rec_base)
            records.append(rec)
            if rec['ok']:
                if new != text:
                    write_text(path, new)
            else:
                bad.append(rec)
        for d in found[g]['delete']:
            path = os.path.join(dist, d)
            rec = {'group': g, 'id': 'delete:' + d, 'target': d, 'expect': 1, 'found': 1 if os.path.isfile(path) else 0,
                   'ok': os.path.isfile(path), 'regex': False, 'phase': 'page'}
            records.append(rec)
            if rec['ok']:
                os.remove(path)
                deleted.append(d)
            else:
                rec['error'] = 'file to delete does not exist in dist'
                bad.append(rec)
    return bad, deleted
