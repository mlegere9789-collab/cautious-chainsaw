#!/usr/bin/env node
// gen-english.mjs - derive tools/historian/data/english-period.v1.txt: the lower-case words that occur at least N times in a public-domain 19th-century prose sample
// (the Official Records vol. 27 OCR sample fetched by tools/historian/ingest, Tier A). Only words are kept - no text, no counts, no sentences - so the list carries none of the source.
// The list is committed; the build reads the committed file only, so a build never depends on the git-ignored cache. Re-run this script only when the dictionary is meant to change.
//   node tools/historian/gen-english.mjs [--cache tmp/historian-cache/<body>] [--min-df 5]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const argv = process.argv.slice(2);
const arg = (k, d) => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : d; };
const cache = path.resolve(root, arg('cache', 'tmp/historian-cache/f11f20ae12aa762c081bfa37941181caf600c8a5.body'));
const minDf = +arg('min-df', 5);
const OUT = path.join(here, 'data/english-period.v1.txt');

if (!fs.existsSync(cache)) { console.error(`cache ${cache} is missing: fetch it with tools/historian/ingest/cli.mjs first (the committed ${path.relative(root, OUT)} is unchanged)`); process.exit(2); }
const text = fs.readFileSync(cache, 'utf8');
const df = new Map();
// a lower-case alphabetic token that is not glued to a capital, digit, apostrophe or hyphen: names are capitalised, OCR debris usually is not a whole lower-case word
for (const m of text.matchAll(/(?<![A-Za-z0-9'’-])[a-z]{3,16}(?![A-Za-z0-9'’-])/g)) df.set(m[0], (df.get(m[0]) || 0) + 1);
const okShape = (w) => /[aeiouy]/.test(w) && !/[^aeiouy]{5,}/.test(w) && !/(.)\1\1/.test(w);
const words = [...df.entries()].filter(([w, n]) => n >= minDf && okShape(w)).map(([w]) => w).sort();
const head = [
  `# english-period.v1.txt - GENERATED by tools/historian/gen-english.mjs (do not edit by hand): lower-case words seen at least ${minDf} times in the Official Records vol. 27 OCR sample (public domain, Tier A).`,
  '# Words only; none of the source text is kept. Used with english-seed.v1.txt so that an ordinary word is never "corrected" into a name.',
];
fs.writeFileSync(OUT, head.join('\n') + '\n' + words.join('\n') + '\n');
console.log(`${words.length} words (of ${df.size} distinct lower-case tokens) written to ${path.relative(root, OUT)}`);
