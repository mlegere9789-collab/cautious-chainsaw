#!/usr/bin/env node
// Tiny checker for the CANDIDATE clock bridge (tools/t0/patches-next/CLOCK.json). No browser is used.
//   1. asserts every anchor against the pristine legacy text (exact count, applied sequentially so an overlap fails loudly)
//   2. writes the patched tree to tmp/time/patched (git-ignored) and parses every script the patches changed (acorn: bundle, chunks, inline page scripts)
//   3. scope check: no NEW unresolved identifier in the patched bundle/chunks (eslint-scope through-references vs the text without CLOCK)
//   4. evaluates the inlined module in a vm and the rewritten functions (getTickTime, JF, QF, HUD date, page clocks) against the model
//   5. re-runs the formula inventory and TM-V2/V9/V16/V17 on the patched tree
//   6. --after-t0 [--position=end|after-B]: first applies tools/t0/patches/*.json in the T0 build system's group order and puts CLOCK at the end or
//      right after group B, so overlaps are detected in both directions (parse/scope are then measured against the T0-only output)
//
//   node tools/time/check-patches.mjs [--file=<CLOCK.json>] [--out=<dir>] [--after-t0] [--position=end|after-B] [--no-scope]
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import * as acorn from 'acorn';
import * as walk from 'acorn-walk';
import { analyze } from 'eslint-scope';
import { P, LEGACY, BUNDLE, readJson, readText, parseArgs } from './lib.mjs';
import { inlineScripts, countOf, pageFunction } from './extract.mjs';
import model from '../../src/lib/time/index.js';
import { buildContext, runAll } from './rules.mjs';

const { flags } = parseArgs(process.argv.slice(2));
const FILE = flags.file ? path.resolve(String(flags.file)) : P('tools', 't0', 'patches-next', 'CLOCK.json');
const OUT = flags.out ? path.resolve(String(flags.out)) : P('tmp', 'time', 'patched');
const BUNDLE_TARGETS = ['js', 'help', 'book', 'css'];
const CHUNKS = { js: BUNDLE, help: 'assets/HelpModal-CFV9T0zH.js', book: 'assets/BookmarkPanel-C5YT4b5k.js', css: 'assets/index-B4G7Z_2G.css' };
const relOf = (target) => CHUNKS[target] || target;
const problems = [], notes = [];
const fail = (m) => problems.push(m);

// ------------------------------------------------------------------ load and validate the patch file (the T0 loader's rules)
const spec = readJson(FILE);
if (typeof spec.group !== 'string' || !Array.isArray(spec.patches)) { console.error('patch file must be {group, patches:[...]}'); process.exit(2); }
const extraTop = Object.keys(spec).filter((k) => !['group', 'patches', 'delete', 'train', 'description'].includes(k)); if (extraTop.length) fail(`unknown top-level keys ${extraTop}`);
const ids = new Set();
for (const p of spec.patches) {
  for (const k of ['id', 'target', 'find', 'repl', 'expect']) if (p[k] === undefined) fail(`${p.id || '?'}: missing ${k}`);
  if (ids.has(p.id)) fail(`${p.id}: duplicate id`); ids.add(p.id);
  if (typeof p.find !== 'string' || !p.find) fail(`${p.id}: empty find`);
  if (!Number.isInteger(p.expect) || p.expect < 1) fail(`${p.id}: expect must be an integer >= 1`);
  if (p.regex && /\(\?P</.test(p.find)) fail(`${p.id}: Python-only regex syntax`);
  if (p.regex && /\\/.test(p.repl)) fail(`${p.id}: regex repl contains a backslash (m.expand would interpret it)`);
  if (!(BUNDLE_TARGETS.includes(p.target) || /^[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*$/.test(p.target))) fail(`${p.id}: target ${p.target} is neither js/help/book/css nor a relative dist path`);
  if (/^(sw\.js|version\.json)$|^(_ops|assets)\//.test(p.target)) fail(`${p.id}: target ${p.target} is generated by the T0 build`);
  const extra = Object.keys(p).filter((k) => !['id', 'target', 'find', 'repl', 'expect', 'regex', 'note'].includes(k)); if (extra.length) fail(`${p.id}: unexpected keys ${extra}`);
}

// ------------------------------------------------------------------ apply
function pyExpand(m, repl) { return repl.replace(/\\g<(\w+)>/g, (_, n) => (m.groups && m.groups[n]) || '').replace(/\\(\d)/g, (_, i) => m[+i] || ''); }
const pristine = (rel) => readText(path.join(LEGACY, rel));
const get = (st, rel) => { if (!st.has(rel)) st.set(rel, pristine(rel)); return st.get(rel); };
function applyPatch(st, p, log) {
  const rel = relOf(p.target), t = get(st, rel);
  let n, out;
  if (p.regex) {
    let re; try { re = new RegExp(p.find, 'g'); } catch { log(`${p.id}: regex does not compile in JS (Python-only syntax?)`); return false; }
    n = [...t.matchAll(re)].length; out = t.replace(re, (...m) => pyExpand(m, p.repl));
  } else { n = countOf(t, p.find); out = t.split(p.find).join(p.repl); }
  if (n !== p.expect) { log(`${p.id}: expected ${p.expect}, found ${n} in ${rel}`); return false; }
  st.set(rel, out); return true;
}
function t0Groups() {
  const cfg = readJson(P('tools', 't0', 'trains.json')), dir = P('tools', 't0', 'patches'), groups = {};
  if (fs.existsSync(dir)) {
    const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json') && !f.startsWith('PG-')).sort();
    for (const g of cfg.group_order) groups[g] = [...files.filter((f) => f === g + '.json'), ...files.filter((f) => f.startsWith(g + '+'))].flatMap((f) => readJson(path.join(dir, f)).patches);
  }
  return { order: cfg.group_order, groups };
}
const position = flags.position || 'end';
/** withClock=false gives the baseline (legacy, or legacy + T0 groups); true adds CLOCK. */
function build(withClock) {
  const st = new Map(); let t0Applied = 0, applied = 0; const t0Failed = [], clockFailed = [];
  const runClock = () => { for (const p of spec.patches) if (applyPatch(st, p, (m) => clockFailed.push(m))) applied++; };
  if (flags['after-t0']) {
    const { order, groups } = t0Groups();
    for (const g of order) {
      for (const p of groups[g] || []) {
        const q = { ...p, id: 't0:' + p.id };
        if (q.regex) {
          try { const re = new RegExp(q.find, 'g'), rel = relOf(q.target), t = get(st, rel), ms = [...t.matchAll(re)]; if (ms.length !== q.expect) { t0Failed.push(q.id); continue; } st.set(rel, t.replace(re, (...m) => pyExpand(m, q.repl))); t0Applied++; } catch { t0Failed.push(q.id + ' (Python regex not emulated)'); }
        } else if (applyPatch(st, q, () => t0Failed.push(q.id))) t0Applied++;
      }
      if (withClock && position === 'after-' + g) runClock();
    }
    if (withClock && position === 'end') runClock();
  } else if (withClock) runClock();
  return { st, t0Applied, t0Failed, clockFailed, applied };
}
const base = build(false), patched = build(true);
for (const m of patched.clockFailed) fail(m);
if (flags['after-t0']) notes.push(`--after-t0 --position=${position}: ${patched.t0Applied} T0 patches applied in the build system's order; ${patched.t0Failed.length} did not apply in this emulation${patched.t0Failed.length ? ': ' + patched.t0Failed.slice(0, 10).join(', ') : ''}`);

// ------------------------------------------------------------------ write the patched tree
fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(LEGACY, OUT, { recursive: true, filter: (s) => !/[\\/](screenshots|icons)([\\/]|$)/.test(s) && !/\.(png|pdf|ico)$/.test(s) });
for (const [rel, text] of patched.st) fs.writeFileSync(path.join(OUT, rel), text);
const baseText = (rel) => (base.st.has(rel) ? base.st.get(rel) : pristine(rel));
const changed = [...patched.st.keys()].filter((rel) => patched.st.get(rel) !== baseText(rel));
const texts = patched.st;

// ------------------------------------------------------------------ syntax
const synt = [];
for (const rel of changed) {
  const text = texts.get(rel);
  try {
    if (rel.endsWith('.js')) acorn.parse(text, { ecmaVersion: 'latest', sourceType: 'module' });
    else for (const s of inlineScripts(text)) acorn.parse(s.text, { ecmaVersion: 'latest', sourceType: 'script' });
    synt.push(`${rel}: parses`);
  } catch (e) { fail(`${rel}: syntax error after patching: ${e.message}`); }
}

// ------------------------------------------------------------------ scope check (new unresolved identifiers)
const BROWSER_GLOBALS = new Set(['window', 'document', 'globalThis', 'self', 'console']); // legitimate globals a patch may introduce; any other new free name is a scope mistake
function unresolved(text) {
  const ast = acorn.parse(text, { ecmaVersion: 'latest', sourceType: 'module', ranges: true });
  return new Set(analyze(ast, { ecmaVersion: 2022, sourceType: 'module' }).globalScope.through.map((r) => r.identifier.name));
}
let scopeNote = 'skipped (--no-scope)';
if (!flags['no-scope']) {
  const t = Date.now(), delta = []; let checked = 0;
  const jsChanged = changed.filter((r) => r.endsWith('.js'));
  for (const rel of jsChanged) {
    const before = unresolved(baseText(rel)), after = unresolved(texts.get(rel)); checked += after.size;
    for (const n of after) if (!before.has(n) && !BROWSER_GLOBALS.has(n)) delta.push(`${rel}: ${n}`);
  }
  for (const d of delta) fail(`new unresolved identifier ${d}`);
  scopeNote = `${delta.length ? delta.length + ' NEW' : 'no new'} unresolved identifiers in ${jsChanged.length} changed scripts (${checked} free names inspected, ${((Date.now() - t) / 1000).toFixed(0)} s)`;
}

// ------------------------------------------------------------------ evaluate the inlined module and the rewritten functions
const STYLES = ['compat', 'chip', 'time', 'day', 'date', 'long', 'short', 'aria', 'frame'];
const bundle = texts.get(BUNDLE);
const evals = [];
const gtCtx = () => ({ f: (t, s) => model.tickToLabel(+t || 1, { style: s || 'compat' }), after: (t, d) => model.tickAfterMinutes(+t || 1, d), hour: (t) => model.hour(+t || 1), tabStart: (d) => model.tabStart(d), tickMax: model.tickMax });
{
  const m = /var GTBGT=(\(function\(\)\{[\s\S]*?\}\)\(\));(?=function v4\()/.exec(bundle);
  if (!m) fail('inlined module not found in the patched bundle');
  else {
    const sb = { window: {} }; vm.createContext(sb); vm.runInContext('var GTBGT=' + m[1] + ';', sb);
    let bad = 0;
    for (let t = 1; t <= model.tickMax; t++) for (const s of STYLES) if (vm.runInContext(`GTBGT.f(${t},${JSON.stringify(s)})`, sb) !== model.tickToLabel(t, { style: s })) bad++;
    for (let t = 1; t <= model.tickMax; t++) { if (vm.runInContext(`GTBGT.after(${t},60)`, sb) !== model.tickAfterMinutes(t, 60) || vm.runInContext(`GTBGT.after(${t},-60)`, sb) !== model.tickAfterMinutes(t, -60)) bad++; if (Math.abs(vm.runInContext(`GTBGT.hour(${t})`, sb) - model.hour(t)) > 1e-12) bad++; }
    for (const v of ['0', '676', 'NaN', '-3', '1e9', '538.5', '"x"', 'undefined', 'null']) { try { vm.runInContext(`GTBGT.f(${v},"compat")`, sb); } catch { bad++; } }
    evals.push(`inline module parity: ${bad ? bad + ' MISMATCHES' : `${model.tickMax} ticks x ${STYLES.length} styles, after(+-60), hour, hostile inputs: identical to src/lib/time`}`); if (bad) fail('inline module differs from the source module');
  }
}
function evalIn(code, gt) { const sb = Object.assign({ Math, String }, { GTBGT: gt, GTBGTime: gt }); vm.createContext(sb); return vm.runInContext(code, sb); }
{
  const gt = gtCtx();
  const ast = acorn.parse(bundle, { ecmaVersion: 'latest', sourceType: 'module' });
  const fnSrc = (name) => { let hit = null; walk.simple(ast, { FunctionDeclaration(n) { if (n.id && n.id.name === name && !hit) hit = n; } }); return hit ? bundle.slice(hit.start, hit.end) : null; };
  let bad = 0;
  const JF = fnSrc('JF'), QF = fnSrc('QF');
  if (!JF || !QF) fail('JF/QF not found after patching');
  else for (const t of [1, 12, 28, 160, 226, 267, 451, 538, 675]) { if (evalIn(`(${JF.replace(/^function JF/, 'function')})(${t},1)`, gt) !== model.tickToLabel(t, { style: 'compat' })) bad++; if (evalIn(`(${QF.replace(/^function QF/, 'function')})(${t})`, gt) !== model.tickToLabel(t, { style: 'compat' })) bad++; }
  let prop = null; walk.simple(ast, { Property(n) { if (!prop && n.key && n.key.name === 'getTickTime') prop = n; } });
  const src = bundle.slice(prop.value.start, prop.value.end);
  for (const t of [1, 12, 160, 226, 538, 675]) { const s = evalIn(`((f)=>(${src})())(()=>({currentTick:${t}}))`, gt); if (s !== model.tickToLabel(t, { style: 'compat' })) bad++; if (s.split(', ')[1] === undefined || /1863/.test(s)) bad++; }
  evals.push(`rewritten getTickTime, JF, QF evaluate to the module strings (mobile split(", ")[1] is the time, never 1863): ${bad ? bad + ' MISMATCHES' : 'ok'}`); if (bad) fail('rewritten bundle functions differ from the module');
  const hud = /R=GTBGT\.f\(x,"date"\)/.test(bundle); evals.push(`HUD date expression routed: ${hud}`); if (!hud) fail('HUD patch missing');
}
for (const [rel, fn] of [['compare.html', 'approxTimeForTick'], ['living-ledger.html', 'timeForTick'], ['camera.html', 'hourForTick'], ['immersive.html', 'hourForTick']]) {
  const f = pageFunction(texts.get(rel), fn);
  if (!f) { fail(`${rel}: ${fn} not found`); continue; }
  const gt = gtCtx(); let bad = 0;
  for (const t of [1, 12, 160, 226, 538, 675]) { const r = evalIn(`(${f.src.replace(/^function \w+/, 'function')})(${t})`, gt); const want = fn === 'hourForTick' ? model.hour(t) : model.tickToLabel(t, { style: rel.startsWith('compare') ? 'chip' : 'compat' }); if (r !== want) bad++; }
  evals.push(`${rel} ${fn}: ${bad ? bad + ' MISMATCHES' : 'evaluates to the module'}`); if (bad) fail(`${rel} ${fn} differs`);
}

// ------------------------------------------------------------------ inventory and validators on the patched tree
const anchorsDoc = readJson(P('data-src', 'time', 'time_anchors.json'));
const rb = Object.fromEntries(runAll(buildContext(model, anchorsDoc)).map((r) => [r.id, r])), ra = Object.fromEntries(runAll(buildContext(model, anchorsDoc, { tree: OUT })).map((r) => [r.id, r]));
const cmpRows = ['TM-V2', 'TM-V9', 'TM-V16', 'TM-V17', 'TM-V18'].map((id) => [id, rb[id].count, ra[id].count]);
let surf = ''; try { surf = execFileSync(process.execPath, [P('tools', 'time', 'surfaces.mjs'), '--root=' + OUT], { encoding: 'utf8' }); } catch (e) { surf = String(e.stdout || e.message); }
const rowsOf = surf.split('\n').filter((l) => /^\| [A-I] \|/.test(l));
const remaining = rowsOf.filter((l) => /\| no \|/.test(l)).map((l) => l.split('|').slice(1, 3).map((x) => x.trim()).join(' '));
const routedN = rowsOf.filter((l) => /\| yes \|/.test(l)).length, unatt = (/Unattributed tick formulas: (\d+)/.exec(surf) || [])[1];

// ------------------------------------------------------------------ report
const delta = texts.get(BUNDLE).length - baseText(BUNDLE).length;
console.log(`CLOCK bridge check: ${spec.patches.length} patches in group "${spec.group}" (${spec.patches.filter((p) => p.regex).length} regex), ${patched.applied} applied${flags['after-t0'] ? ' on top of the T0 groups' : ' to the pristine legacy text'}, ${changed.length} files changed`);
console.log(synt.join('\n'));
console.log('scope: ' + scopeNote);
console.log(evals.join('\n'));
console.log('validators, legacy -> patched: ' + cmpRows.map((r) => `${r[0]} ${r[1]} -> ${r[2]}`).join('; '));
console.log(`formula inventory on the patched tree: ${rowsOf.length} implementations found, ${routedN} routed through the module, ${remaining.length} still legacy (unattributed formulas: ${unatt}): ${remaining.join('; ') || 'none'}`);
console.log(`bundle size delta from CLOCK: +${delta} bytes`);
for (const n of notes) console.log(n);
if (problems.length) console.error(`\n${problems.length} PROBLEM(S):\n  ` + problems.join('\n  '));
fs.mkdirSync(P('tools', 'time', 'build'), { recursive: true });
if (!flags.out) fs.writeFileSync(P('tools', 'time', 'build', 'clock-patch-report.json'), JSON.stringify({ patches: spec.patches.length, applied: patched.applied, changed, problems, notes, evals, validators: cmpRows, remaining, bundleDelta: delta }, null, 1) + '\n');
process.exit(problems.length ? 1 : 0);
