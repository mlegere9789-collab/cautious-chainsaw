const norm = (s) => s.replace(/\s+/g, ' ');
const ctxOf = (text, i, len) => norm(text.slice(Math.max(0, i - 50), i + len + 50)).trim();

// ------------------------------------------------------------------ scanning primitives
/** scan one text blob; push findings. `base` offsets the line number (whole-file offset of the blob) */
function scanText(text, meta, out, { rules = RULES } = {}) {
  for (const rule of rules) {
    rule.re.lastIndex = 0;
    let m;
    while ((m = rule.re.exec(text))) {
      if (m[0] === '') { rule.re.lastIndex++; continue; }
      let line = null; let abs = null;
      if (meta.fullText != null) { abs = (meta.offset || 0) + m.index; line = meta.fullText.slice(0, abs).split('\n').length; }
      else if (meta.lineBase != null) line = meta.lineBase + text.slice(0, m.index).split('\n').length - 1;
      out.push({ file: meta.file, where: meta.where || 'text', rule: rule.id, match: m[0], line, abs, context: ctxOf(text, m.index, m[0].length), tight: norm(text.slice(Math.max(0, m.index - 24), m.index + m[0].length + 16)).trim() });
    }
  }
}
const printableStrings = (buf, min = 8) => {
  const s = [];
  const a = buf.toString('latin1');
  for (const m of a.matchAll(new RegExp(`[\\x20-\\x7e\\t\\r\\n]{${min},}`, 'g'))) s.push(m[0]);
  for (const m of a.matchAll(new RegExp(`(?:[\\x20-\\x7e]\\x00){${min},}`, 'g'))) s.push(m[0].replace(/\x00/g, ''));
  return s.join('\n');
};

function jsPieces(src) {
  /** [{text, offset, kind}] of string literals, template text and comments */
  const pieces = [];
  if (acorn) {
    try {
      const comments = [];
      const tok = acorn.tokenizer(src, { ecmaVersion: 'latest', sourceType: 'module', allowHashBang: true, onComment: (block, text, start) => comments.push({ text, offset: start, kind: 'js-comment' }) });
      for (const t of tok) {
        if (t.type.label === 'string' || t.type.label === 'template') pieces.push({ text: String(t.value), offset: t.start, kind: t.type.label === 'string' ? 'js-string' : 'js-template' });
      }
      return pieces.concat(comments);
    } catch (e) {
      pieces.length = 0; pieces.push({ text: '', offset: 0, kind: 'js-tokenizer-failed', error: e.message });
    }
  }
  // fallback: quoted strings and comments by regex (less precise, still never looks at bare identifiers)
  for (const m of src.matchAll(/"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'|`((?:[^`\\]|\\.)*)`/g)) pieces.push({ text: m[1] ?? m[2] ?? m[3], offset: m.index, kind: 'js-string' });
  for (const m of src.matchAll(/\/\*[\s\S]*?\*\/|(?<![:"'\w])\/\/[^\n]*/g)) pieces.push({ text: m[0], offset: m.index, kind: 'js-comment' });
  return pieces;
}

function scanJs(src, meta, out) {
  const pieces = jsPieces(src);
  const failed = pieces.find((p) => p.kind === 'js-tokenizer-failed');
  if (failed) out.push({ file: meta.file, where: 'js', rule: 'scan-error', match: '', line: null, context: `acorn tokenizer failed (${failed.error}); regex fallback used` , severity: 'info' });
  for (const p of pieces) { if (p.kind === 'js-tokenizer-failed') continue; scanText(p.text, { file: meta.file, where: meta.where ? `${meta.where}/${p.kind}` : p.kind, fullText: src, offset: (meta.offset || 0) + p.offset }, out); }
}

function scanHtml(src, meta, out) {
  // inline scripts: javascript -> string literals only; json (ld+json, importmap, module data) -> raw text; everything else is scanned raw
  let rest = ''; let last = 0;
  for (const m of src.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    const attrs = m[1], body = m[2]; const bodyStart = m.index + m[0].indexOf('>') + 1;
    rest += src.slice(last, bodyStart) + ' '.repeat(0); last = bodyStart + body.length;
    const type = (/\btype\s*=\s*["']?([^\s"'>]+)/i.exec(attrs) || [])[1] || 'text/javascript';
    if (/json/i.test(type)) scanText(body, { file: meta.file, where: 'html/inline-json', fullText: src, offset: bodyStart }, out);
    else if (/javascript|module|ecmascript/i.test(type) || !type) scanJs(body, { file: meta.file, where: 'html/inline-script', offset: bodyStart }, out);
    else scanText(body, { file: meta.file, where: `html/inline-${type}`, fullText: src, offset: bodyStart }, out);
  }
  rest += src.slice(last);
  // the rest of the document with script bodies blanked (preserve newlines so line numbers stay right)
  const blanked = src.replace(/(<script\b[^>]*>)([\s\S]*?)(<\/script\s*>)/gi, (_, a, b, c) => a + b.replace(/[^\n]/g, ' ') + c);
  // classify where in the document the match sits (comment / attribute of a tag / meta tag / title / text)
  const tmp = [];
  scanText(blanked, { file: meta.file, where: 'html', fullText: blanked, offset: 0 }, tmp);
  for (const f of tmp) {
    const at = f.abs;
    const inComment = blanked.lastIndexOf('<!--', at) > blanked.lastIndexOf('-->', at);
    const lt = blanked.lastIndexOf('<', at), gt = blanked.lastIndexOf('>', at);
    const inTag = !inComment && lt > gt;
    const tagName = inTag ? (/^<\/?([a-zA-Z][\w:-]*)/.exec(blanked.slice(lt)) || [])[1] : null;
    const title = !inTag && !inComment && /<title\b[^>]*>[^<]*$/i.test(blanked.slice(Math.max(0, at - 300), at));
    f.where = inComment ? 'html/comment' : inTag ? (/^meta$/i.test(tagName) ? 'html/meta-tag' : `html/attribute(${tagName})`) : title ? 'html/title' : 'html/visible-text-or-style';
    out.push(f);
  }
}

// ------------------------------------------------------------------ image metadata
function pngSegments(buf) {
  const seg = [];
  if (buf.length < 8 || buf.readUInt32BE(0) !== 0x89504e47) return seg;
  let p = 8; const plain = new Set(['IHDR', 'PLTE', 'IDAT', 'IEND', 'tRNS', 'gAMA', 'cHRM', 'sRGB', 'sBIT', 'pHYs', 'bKGD', 'hIST', 'tIME', 'acTL', 'fcTL', 'fdAT', 'sPLT', 'cICP', 'mDCV', 'cLLI']);
  while (p + 8 <= buf.length) {
    const len = buf.readUInt32BE(p), type = buf.toString('latin1', p + 4, p + 8); const d = buf.subarray(p + 8, p + 8 + len);
    if (type === 'tEXt') { const z = d.indexOf(0); seg.push({ kind: `png:tEXt:${d.toString('latin1', 0, z)}`, text: d.toString('latin1', z + 1) }); }
    else if (type === 'zTXt') { const z = d.indexOf(0); let t = ''; try { t = require('node:zlib').inflateSync(d.subarray(z + 2)).toString('utf8'); } catch { t = '(undecodable)'; } seg.push({ kind: `png:zTXt:${d.toString('latin1', 0, z)}`, text: t }); }
    else if (type === 'iTXt') {
      const z = d.indexOf(0); const comp = d[z + 1]; let q = z + 3; q = d.indexOf(0, q) + 1; q = d.indexOf(0, q) + 1;
      let t = d.subarray(q); if (comp) { try { t = require('node:zlib').inflateSync(t); } catch { t = Buffer.from('(undecodable)'); } }
      seg.push({ kind: `png:iTXt:${d.toString('latin1', 0, z)}`, text: t.toString('utf8') });
    } else if (type === 'iCCP') { const z = d.indexOf(0); seg.push({ kind: 'png:iCCP-name', text: d.toString('latin1', 0, z) }); }
    else if (type === 'eXIf') seg.push({ kind: 'png:eXIf', text: printableStrings(d, 4) });
    else if (!plain.has(type)) seg.push({ kind: `png:chunk:${type}`, text: printableStrings(d, 4) });
    p += 12 + len;
    if (type === 'IEND') break;
  }
  if (p < buf.length) seg.push({ kind: 'png:after-IEND', text: printableStrings(buf.subarray(p), 4) });
  return seg;
}
function jpegSegments(buf) {
  const seg = []; if (buf[0] !== 0xff || buf[1] !== 0xd8) return seg;
  let p = 2;
  while (p + 4 <= buf.length) {
    if (buf[p] !== 0xff) break;
    const m = buf[p + 1]; if (m === 0xd9) { p += 2; break; } if (m === 0xda) break;
    const len = buf.readUInt16BE(p + 2); const d = buf.subarray(p + 4, p + 2 + len);
    if (m === 0xfe) seg.push({ kind: 'jpeg:COM', text: d.toString('utf8') });
    else if (m >= 0xe1 && m <= 0xef) seg.push({ kind: `jpeg:APP${m - 0xe0}`, text: /xpacket|<x:xmp|http:\/\/ns\.adobe/.test(d.toString('latin1', 0, 400)) ? d.toString('utf8') : printableStrings(d, 4) });
    p += 2 + len;
  }
  // bytes after EOI
  const eoi = buf.lastIndexOf(Buffer.from([0xff, 0xd9]));
  if (eoi >= 0 && eoi + 2 < buf.length) seg.push({ kind: 'jpeg:after-EOI', text: printableStrings(buf.subarray(eoi + 2), 4) });
  return seg;
}
function webpSegments(buf) {
  const seg = []; if (buf.toString('latin1', 0, 4) !== 'RIFF') return seg;
  let p = 12; while (p + 8 <= buf.length) {
    const t = buf.toString('latin1', p, p + 4), len = buf.readUInt32LE(p + 4); const d = buf.subarray(p + 8, p + 8 + len);
    if (t === 'EXIF' || t === 'XMP ' || t === 'ICCP') seg.push({ kind: `webp:${t.trim()}`, text: t === 'XMP ' ? d.toString('utf8') : printableStrings(d, 4) });
    p += 8 + len + (len & 1);
  }
  return seg;
}
function gifSegments(buf) {
  const seg = []; if (buf.toString('latin1', 0, 3) !== 'GIF') return seg;
  const s = buf.toString('latin1');
  for (const m of s.matchAll(/\x21\xfe([\s\S]*?)\x00/g)) seg.push({ kind: 'gif:comment', text: m[1] });
  for (const m of s.matchAll(/\x21\xff\x0b(.{11})/gs)) seg.push({ kind: 'gif:application-ext', text: m[1] });
  return seg;
}
function imageSegments(ext, buf) {
  const sig4 = buf.subarray(0, 4);
  if (sig4.readUInt32BE(0) === 0x89504e47) return pngSegments(buf);
  if (buf[0] === 0xff && buf[1] === 0xd8) return jpegSegments(buf);
  if (buf.toString('latin1', 0, 4) === 'RIFF') return webpSegments(buf);
  if (buf.toString('latin1', 0, 3) === 'GIF') return gifSegments(buf);
  return [{ kind: `${ext.slice(1)}:strings`, text: printableStrings(buf, 8) }];
}

// ------------------------------------------------------------------ PDF
function auditPdf(file, abs, out, notes) {
  const r = runCmd('python', ['-I', path.join(ACCEPT, 'pdf_probe.py'), abs], { timeoutMs: 120000 });
  let j = null; try { j = JSON.parse(r.stdout); } catch { /* handled below */ }
  if (!j || !j.ok) { out.push({ file, where: 'pdf', rule: 'scan-error', match: '', line: null, context: `pdf_probe failed: ${(j && j.errors && j.errors.join('; ')) || r.stderr.slice(0, 200) || 'no output'}` }); }
  else {
    notes.push({ file, pdf: { pages: j.pages, info: j.info, hasXmp: !!j.xmp, fonts: j.fonts, tagged: j.tagged, lang: j.lang } });
    const infos = { ...(j.info_raw || {}), ...(j.info || {}) };
    for (const [k, v] of Object.entries(infos)) {
      scanText(`${v}`, { file, where: `pdf/Info${k}` }, out);
      // Producer/Creator must be empty or exactly the site's name; any other value (a tool, a vendor, a default) is a finding.
      if (/^\/(Producer|Creator)$/.test(k) && String(v).trim() && (PDF_TOOL.test(v) || String(v).trim() !== SITE_NAME)) {
        out.push({ file, where: `pdf/Info${k}`, rule: 'pdf producer/creator tool name', match: String(v), line: null, context: `${k} = ${v}${PDF_TOOL.test(v) ? '' : '  (non-empty and not the site name: name the site or leave it empty)'}` });
      }
      if (k === '/Author' && String(v).trim() && PDF_TOOL.test(v)) out.push({ file, where: 'pdf/Info/Author', rule: 'pdf producer/creator tool name', match: String(v), line: null, context: `${k} = ${v}` });
      if (k === '/Title' && !String(v).trim()) out.push({ file, where: 'pdf/Info/Title', rule: 'pdf title missing', match: '', line: null, context: 'Title is empty (screen readers announce the file name)' });
    }
    if (!('/Title' in infos)) out.push({ file, where: 'pdf/Info/Title', rule: 'pdf title missing', match: '', line: null, context: 'no Title in the Info dictionary' });
    if (j.xmp) scanText(j.xmp, { file, where: 'pdf/xmp' }, out);
    j.text.forEach((t, i) => scanText(t, { file, where: `pdf/text/p${i + 1}` }, out));
    for (const t of j.outline || []) scanText(t, { file, where: 'pdf/outline' }, out);
    for (const l of j.links || []) scanText(JSON.stringify(l), { file, where: `pdf/link/p${l.page}` }, out);
    for (const a of Object.keys(j.attachments || {})) out.push({ file, where: 'pdf/attachment', rule: 'embedded file in pdf', match: a, line: null, context: `embedded file ${a}` });
    for (const f of j.fonts || []) scanText(f, { file, where: 'pdf/font' }, out);
  }
  // Raw strings of the file OUTSIDE stream bodies: compressed stream bytes are noise (a random 2-byte run can spell "AI").
  // What a stream carries that matters is scanned decoded above: page text, XMP, outline, links, attachments, fonts.
  const rawBuf = fs.readFileSync(abs);
  const outside = Buffer.from(rawBuf.toString('latin1').replace(/(\r?\n)stream\r?\n[\s\S]*?\r?\nendstream/g, '$1stream\nendstream'), 'latin1');
  scanText(printableStrings(outside, 6), { file, where: 'pdf/raw-strings' }, out);
}

// ------------------------------------------------------------------ whitelist
const globRe = (g) => new RegExp('^' + g.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*\*/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\u0000/g, '.*') + '$');
export function loadWhitelist(f) {
  if (!f || !fs.existsSync(f)) return [];
  const j = JSON.parse(fs.readFileSync(f, 'utf8'));
  return (Array.isArray(j) ? j : j.entries || []).map((e) => {
    if (!e.file || !e.regex || !e.reason) throw new Error(`whitelist entry needs file, regex and reason: ${JSON.stringify(e)}`);
    return { ...e, fileRe: globRe(e.file), re: new RegExp(e.regex, e.flags || 'i') };
  });
}

// ------------------------------------------------------------------ main audit
/** audit({zip, dir, whitelist}) -> {findings, whitelisted, scanned:{files,bytes}, notes, errors} ; if only `zip` is given it is extracted to a throw-away dir */
export function audit({ zip = null, dir = null, whitelist = [] } = {}) {
  const raw = []; const notes = []; const info = [];
  let tmp = null; let zipInfo = null;
  if (zip) {
    const buf = fs.readFileSync(zip); const z = readZip(buf); zipInfo = { entries: z.entries.length, comment: z.comment };
    if (z.comment) scanText(z.comment, { file: '(zip comment)', where: 'zip/comment' }, raw), raw.push({ file: '(zip comment)', where: 'zip/comment', rule: 'zip comment present', match: z.comment, line: null, context: z.comment.slice(0, 120) });
    for (const e of z.entries) {
      scanText(e.name, { file: e.name, where: 'zip/entry-name' }, raw);
      if (e.comment) { scanText(e.comment, { file: e.name, where: 'zip/entry-comment' }, raw); raw.push({ file: e.name, where: 'zip/entry-comment', rule: 'zip entry comment present', match: e.comment, line: null, context: e.comment.slice(0, 120) }); }
    }
    if (!dir) { tmp = freshTmp('copyaudit'); const ex = extractZip(zip, tmp); dir = tmp; for (const pr of ex.problems) raw.push({ file: '(zip)', where: 'zip', rule: 'scan-error', match: '', line: null, context: pr }); }
  }
  const files = walk(dir);
  let bytes = 0;
  for (const rel of files) {
    const abs = path.join(dir, ...rel.split('/')); const buf = fs.readFileSync(abs); bytes += buf.length;
    const ext = path.extname(rel).toLowerCase();
    if (!zip) scanText(rel, { file: rel, where: 'path' }, raw);
    if (INTERNAL_FILE.test(rel)) raw.push({ file: rel, where: 'path', rule: 'internal doc/notes/source-map file shipped', match: rel, line: null, context: rel });
    if (rel.startsWith('_ops/')) info.push({ file: rel, where: 'path', rule: 'ops file shipped (info)', match: rel, line: null, context: `${rel} is deployed to the public site`, severity: 'info' });
    try {
      if (ext === '.js' || ext === '.mjs' || ext === '.cjs') scanJs(buf.toString('utf8'), { file: rel }, raw);
      else if (ext === '.html' || ext === '.htm') scanHtml(buf.toString('utf8'), { file: rel }, raw);
      else if (ext === '.pdf') auditPdf(rel, abs, raw, notes);
      else if (IMG_EXT.has(ext)) {
        for (const s of imageSegments(ext, buf)) scanText(s.text, { file: rel, where: s.kind }, raw);
      } else if (TEXT_EXT.has(ext) || ext === '' || /^_(headers|redirects)$/.test(rel)) {
        const txt = buf.toString('utf8');
        // binary disguised as text (a NUL in the first 4 KB): strings scan
        if (buf.subarray(0, 4096).includes(0)) scanText(printableStrings(buf, 8), { file: rel, where: 'binary-strings' }, raw);
        else scanText(txt, { file: rel, where: ext === '.map' ? 'sourcemap' : (rel.startsWith('_') ? 'config-file' : ext.slice(1) || 'text'), fullText: txt, offset: 0 }, raw);
      } else scanText(printableStrings(buf, 8), { file: rel, where: 'binary-strings' }, raw);
    } catch (e) {
      raw.push({ file: rel, where: 'scan', rule: 'scan-error', match: '', line: null, context: `could not scan: ${e.message}` });
    }
  }
  // de-duplicate (same file/rule/line/context from overlapping scans) and apply the whitelist
  const seen = new Set(); const findings = []; const whitelisted = [];
  for (const f of raw.concat(info)) {
    const key = `${f.file}|${f.rule}|${f.line}|${f.context}|${f.where}`;
    if (seen.has(key)) continue; seen.add(key);
    if (f.severity === 'info') { f.informational = true; }
    const w = whitelist.find((e) => e.fileRe.test(f.file) && (!e.rule || e.rule === f.rule) && (e.re.test(f.tight || f.context) || e.re.test(f.match)));
    if (w) whitelisted.push({ ...f, whitelistReason: w.reason }); else findings.push(f);
  }
  if (tmp) { try { fs.rmSync(tmp, { recursive: true, force: true }); } catch { /* best effort */ } }
  const blocking = findings.filter((f) => !f.informational && f.rule !== 'scan-error' || f.rule === 'scan-error');
  return { findings, blocking: findings.filter((f) => !f.informational), informational: findings.filter((f) => f.informational), whitelisted, scanned: { files: files.length, bytes }, zip: zipInfo, notes, rules: RULES.map((r) => r.id) };
}

// ------------------------------------------------------------------ CLI
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const args = parseArgs(process.argv.slice(2), { quiet: 'bool', 'show-whitelisted': 'bool' });
  const target = args._[0];
  if (!target) { console.error('usage: node tools/accept/copy_audit.mjs <candidate.zip | dist-dir> [--whitelist file] [--json out] [--quiet] [--show-whitelisted]'); process.exit(2); }
  const abs = path.resolve(target);
  const wl = loadWhitelist(path.resolve(args.whitelist || path.join(ACCEPT, 'copy_whitelist.json')));
  const isZip = fs.statSync(abs).isFile() && abs.toLowerCase().endsWith('.zip');
  const res = audit({ zip: isZip ? abs : null, dir: isZip ? null : abs, whitelist: wl });
  if (args.json) writeJson(path.resolve(args.json), res);
  if (!args.quiet) {
    const byRule = {};
    for (const f of res.blocking) { (byRule[f.rule] ||= []).push(f); }
    for (const [rule, list] of Object.entries(byRule).sort((a, b) => b[1].length - a[1].length)) {
      console.log(`\n== ${rule}  (${list.length})`);
      for (const f of list.slice(0, 60)) console.log(`  ${f.file}${f.line ? ':' + f.line : ''}  [${f.where}]  ${JSON.stringify(f.match).slice(0, 60)}  ...${f.context.slice(0, 160)}...`);
      if (list.length > 60) console.log(`  ... ${list.length - 60} more (see --json)`);
    }
    if (args['show-whitelisted']) for (const f of res.whitelisted) console.log(`  [whitelisted: ${f.whitelistReason}] ${f.file}${f.line ? ':' + f.line : ''} ${f.rule}`);
  }
  console.log(`\ncopy audit: scanned ${res.scanned.files} files (${(res.scanned.bytes / 1e6).toFixed(1)} MB)${isZip ? `, ${res.zip.entries} zip entries, comment ${res.zip.comment ? 'PRESENT' : 'empty'}` : ''}`);
  console.log(`findings: ${res.blocking.length} blocking, ${res.informational.length} informational, ${res.whitelisted.length} whitelisted`);
  process.exit(res.blocking.length ? 1 : 0);
}
