#!/usr/bin/env node
// tools/accept/copy_audit.mjs - the copy audit of docs/battle-theatre/GOVERNANCE/FINAL-ACCEPTANCE.md, run over EVERY byte class of a candidate.
//
//   node tools/accept/copy_audit.mjs <candidate.zip | dist-dir> [--whitelist tools/accept/copy_whitelist.json] [--json out.json] [--quiet] [--show-whitelisted]
//
// What is scanned (nothing is skipped; an unreadable file is itself a finding):
//   zip            every entry name, the zip comment and every per-entry comment (only when a .zip is given)
//   text           html (visible text, comments, attributes, meta/og tags, inline css), css, json, svg, xml, txt, toml, _headers, _redirects,
//                  webmanifest, md, source maps (json: sources, names, sourcesContent) - raw text with word-boundary rules
//   javascript     .js/.mjs and inline <script>: ONLY string literals, template-literal text and comments are scanned (via acorn's tokenizer),
//                  so minified identifiers such as `Ai` or `agent` as a variable never match
//   pdf            Info dictionary (raw and normalised), XMP packet, text of every page, outline, link URIs, embedded files, font names (pdf_probe.py),
//                  plus the printable strings of the raw file; Producer/Creator/Author/Title are also checked for tool names and defaults
//   images         PNG tEXt/zTXt/iTXt/eXIf/iCCP/unknown ancillary chunks and bytes after IEND, JPEG APPn/COM segments and bytes after EOI, WebP
//                  EXIF/XMP/ICCP chunks, GIF comment/application extensions; SVG is text
//   other binary   printable ASCII / UTF-16LE strings of 8+ characters (fonts, audio tags, ...)
// Rules: see RULES below.  A finding is silenced only by an entry of copy_whitelist.json {file, regex, reason} (file = path or glob, regex tested against
// the finding's context); whitelisted findings are still listed with their reason.  Exit code 1 when any non-whitelisted finding exists.
