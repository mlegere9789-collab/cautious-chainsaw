#!/usr/bin/env node
// Builds the CANDIDATE trust pages (About, Sources and Methods, Standard of Care, Corrections, FAQ, Accessibility Statement,
// Changelog, Contact) as static HTML under candidates/trust-pages/. Inert: nothing in any release tree, trains.json or patch file
// refers to them. Inputs are read-only (data-src/**, docs/**, ops/release-notes, baseline/dist, tools/guide/features.json);
// owner-supplied values come from tools/copy/trust-config.json and are never invented.
//
//   node tools/copy/build-trust-pages.mjs                 write candidates/trust-pages (candidate banner on, owner markers visible)
//   node tools/copy/build-trust-pages.mjs --check         build in memory and compare with what is committed (exit 1 on a difference)
//   node tools/copy/build-trust-pages.mjs --publish       refuse (exit 1) while any [OWNER TO PROVIDE] or [OWNER TO CONFIRM] marker is open;
//                                                        otherwise write pages without the candidate banner
//   options: --out DIR  --config FILE  --list-owner-inputs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { REPO } from './lib/lint.mjs';
import { loadInputs } from './trust/inputs.mjs';
import { buildPages } from './trust/pages.mjs';
import { renderPage, PAGES, CSS } from './trust/template.mjs';

export const DEFAULT_OUT = path.join(REPO, 'candidates', 'trust-pages');
export const DEFAULT_CONFIG = path.join(REPO, 'tools', 'copy', 'trust-config.json');
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');

export function build({ config = DEFAULT_CONFIG, publish = false } = {}) {
  const cfg = JSON.parse(fs.readFileSync(config, 'utf8'));
  const I = loadInputs({ asOf: cfg.asOf });
  const { pages, unresolved, provenancePaths } = buildPages({ I, cfg, publish });
  // every file whose hash is printed on a page is an input: a change to any of them makes the committed pages stale
  const inputs = { ...I.hashes, ...Object.fromEntries(provenancePaths.map((p) => [p, I.sha(p)]).filter(([, h]) => h)) };
  const files = new Map();
  const manifestPages = [];
  for (const slug of PAGES.map((p) => p.slug)) {
    const p = pages[slug];
    if (!p) throw new Error(`page ${slug} was not built`);
    const html = renderPage({ ...p, asOf: cfg.asOf, publish, linkStyle: publish ? cfg.linkStyle : 'html', canonicalStyle: cfg.canonicalStyle, siteUrl: cfg.siteUrl });
    files.set(`${slug}.html`, html);
    const pointers = [...html.matchAll(/data-source="([^"]+)"/g)].flatMap((m) => m[1].split(' '));
    manifestPages.push({ slug, file: `${slug}.html`, bytes: Buffer.byteLength(html), sha256: sha(html), title: p.title, sources: [...new Set(pointers)].sort() });
  }
  // the unresolved list is the same for every page that asks: de-duplicate by key
  const owners = [...new Map(unresolved.map((u) => [u.key, u])).values()].sort((a, b) => (a.key < b.key ? -1 : 1));
  const corrections = { schema: 'gtbg/corrections/1', note: 'The public log of corrections (docs/content/OWNER-INPUTS.md). Entries are added only after a correction is live; none is written in advance.', fields: ['id', 'date', 'where', 'was', 'now', 'source', 'reviewer', 'credit_consent'], entries: [] };
  files.set('trust.css', `${CSS}\n`);
  files.set('corrections.json', JSON.stringify(corrections, null, 2) + '\n');
  files.set('changelog.json', JSON.stringify({ schema: 'gtbg/changelog/1', status: 'unreleased: release trains R0 to R1c are built and tested, not deployed', entries: pages.changelog.changelog.entries }, null, 2) + '\n');
  const manifest = {
    schema: 'gtbg/trust-pages-manifest/1',
    status: publish ? 'PUBLISH BUILD' : 'CANDIDATE: inert, not wired into any release; owner inputs open',
    as_of: cfg.asOf,
    generator: 'node tools/copy/build-trust-pages.mjs',
    inputs,
    claims: I.claims,
    owner_inputs_open: owners,
    pages: manifestPages,
  };
  files.set('trust-manifest.json', JSON.stringify(manifest, null, 2) + '\n');
  files.set('README.md', readme(owners));
  return { files, owners, manifest, I };
}

function readme(owners) {
  return `# Candidate trust pages

Status: CANDIDATE. Inert. Nothing in a release tree, \`tools/t0/trains.json\` or a patch refers to these files.

Generated by \`node tools/copy/build-trust-pages.mjs\` from files of this repository (see \`trust-manifest.json\`: input hashes, the claims the generator checks, the pages with their sources). Do not edit the HTML by hand; change \`tools/copy/trust/pages.mjs\`, \`tools/copy/trust-config.json\` or the inputs and rebuild.

Pages: About, Sources and Methods, Standard of Care, Corrections, FAQ, Accessibility Statement, Changelog, Contact and Report a Problem. Preview them with \`node tools/copy/preview-server.mjs\` (serves this folder with the site's shared menu assets).

Open owner inputs (${owners.length}): see \`docs/content/OWNER-INPUTS.md\`. \`node tools/copy/build-trust-pages.mjs --publish\` refuses to build while any is open.
`;
}

export function writeAll(files, out) {
  fs.mkdirSync(out, { recursive: true });
  for (const [name, content] of files) fs.writeFileSync(path.join(out, name), content);
}

function main(argv = process.argv.slice(2), { log = console.log, err = console.error } = {}) {
  const opt = (n, d) => { const i = argv.indexOf(`--${n}`); return i >= 0 ? argv[i + 1] : d; };
  const out = opt('out') ? path.resolve(opt('out')) : DEFAULT_OUT;
  const config = opt('config') ? path.resolve(opt('config')) : DEFAULT_CONFIG;
  const publish = argv.includes('--publish');
  let r;
  try { r = build({ config, publish }); } catch (e) { err(`cannot build: ${e.message}`); return 2; }
  if (argv.includes('--list-owner-inputs')) { for (const o of r.owners) log(`${o.kind === 'confirm' ? 'CONFIRM' : 'PROVIDE'}  ${o.key}: ${o.label}`); return 0; }
  if (publish && r.owners.length) { err(`refusing to publish: ${r.owners.length} owner input(s) are open`); for (const o of r.owners) err(`  ${o.kind === 'confirm' ? 'CONFIRM' : 'PROVIDE'}  ${o.key}: ${o.label}`); return 1; }
  if (argv.includes('--check')) {
    const diffs = [];
    for (const [name, content] of r.files) { const p = path.join(out, name); if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== content) diffs.push(name); }
    if (diffs.length) { err(`out of date: ${diffs.join(', ')}; run node tools/copy/build-trust-pages.mjs`); return 1; }
    log(`up to date: ${r.files.size} files in ${path.relative(REPO, out)}`); return 0;
  }
  writeAll(r.files, out);
  log(`wrote ${r.files.size} files to ${path.relative(REPO, out)} (${r.manifest.pages.length} pages, ${r.owners.length} owner input(s) open, ${r.manifest.claims.length} claims checked)`);
  for (const p of r.manifest.pages) log(`  ${p.file.padEnd(24)} ${String(p.bytes).padStart(6)} bytes, ${p.sources.length} source pointers`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) process.exit(main());
export { main };
