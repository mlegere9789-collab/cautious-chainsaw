// Machine report: docs/data/baseline-report.md and data-src/build/data-quality-report.json.
// Deterministic: no clock, no absolute paths. Regenerate with `node tools/data/validate.mjs --report docs/data/baseline-report.md`.
import fs from 'node:fs';
import path from 'node:path';
import { rowsOf } from './runner.mjs';
import { buildCrosswalk, buildRegistry, buildDualMeaning } from './registry.mjs';
import { measureSection2, measureExtras } from './measure.mjs';
import { provenanceCoverage } from '../rules/prov_rules.mjs';
import { retiredLiteralHits } from '../rules/facts_rules.mjs';
import { REPO_ROOT, prettyJson } from './util.mjs';

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const n = (x) => (typeof x === 'number' ? x.toLocaleString('en-US') : String(x));

function table(headers, rows) {
  return [`| ${headers.join(' | ')} |`, `|${headers.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map((c) => esc(c)).join(' | ')} |`)].join('\n');
}

function breakdown(violations) {
  const m = new Map();
  for (const v of violations) m.set(v.kind ?? '-', (m.get(v.kind ?? '-') || 0) + 1);
  return [...m].sort((a, b) => b[1] - a[1]).map(([k, c]) => `${k} ${c}`).join(', ');
}

export function writeBaselineReport({ ctx, results, verdict, baseline, treeInfo, outPath, now }) {
  const crosswalk = buildCrosswalk(ctx);
  const byTarget = new Map();
  for (const e of crosswalk.entries) if (e.proposed && !e.new_record) { if (!byTarget.has(e.proposed)) byTarget.set(e.proposed, []); byTarget.get(e.proposed).push(e); }
  const registry = buildRegistry(ctx, byTarget);
  const collisions = buildDualMeaning(ctx, results.get('R011').violations);
  const sec2 = measureSection2(ctx, { crosswalk, registry });
  const extras = measureExtras(ctx);
  const cov = provenanceCoverage(ctx);
  const ran = [...results.values()].filter((r) => r.ran);
  const skipped = [...results.values()].filter((r) => !r.ran);
  const partial = ran.filter((r) => r.rule.status === 'partial');
  const L = [];
  L.push('# Data-quality baseline report');
  L.push('');
  L.push('Generated by `tools/data/validate.mjs --report` (WP-DATA-03). Do not edit by hand: regenerate after any rule, schema, baseline or data change. Every number below was produced by running the validator over the served data tree; nothing was copied from a specialist report except the "expected" columns, which are labelled as such and quoted from chapter 13 / the data-integrity report.');
  L.push('');
  L.push(`- Data tree: \`${treeInfo.dir}\`, ${n(treeInfo.files)} JSON files, ${n(treeInfo.bytes)} bytes, data_version ${treeInfo.data_version}`);
  L.push(`- Content hash (sha256 of the manifest): \`${treeInfo.content_sha256}\``);
  L.push(`- Baseline: \`tools/data/baseline.json\` dated ${now}; ratchet verdict **${verdict.pass ? 'PASS' : 'FAIL'}** (${verdict.failures.length} failures, ${verdict.warnings.length} warnings)`);
  L.push(`- Rules: ${results.size} (${[...results.values()].filter((r) => r.rule.tier === 'core').length} core + ${[...results.values()].filter((r) => r.rule.tier === 'v2').length} v2); ${ran.length} ran, ${skipped.length} skipped with a stated reason, ${partial.length} of the ran rules are PARTIAL (see notes)`);
  L.push('');
  L.push('## 1. What this baseline means');
  L.push('');
  L.push('The legacy tree is frozen and is known to be defective (chapter 13). This report does not say the data is acceptable; it records **today\'s known violations** so that CI can fail on any *new* violation, on any baseline entry that no longer occurs (a fix must delete exactly its entry), and on entries past their expiry. `E` rules fail the build on a new violation; `W` rules warn (`--strict` makes them fail). A rule that could not run is listed as SKIPPED and is never counted as clean.');
  L.push('');
  L.push('## 2. Rule results');
  L.push('');
  const rows = [...results.values()].map((r) => {
    const rule = r.rule;
    const b = baseline.rules[rule.id];
    return [rule.id, rule.sev, r.ran ? rule.status : 'SKIPPED', rule.dv.join(' ') || '-', r.ran ? n(r.violations.length) : '-', r.ran ? n(rowsOf(r.violations)) : '-', b ? n(b.count) : '0', b?.expires ?? '-', rule.wp, r.ran ? breakdown(r.violations) : `skipped: ${r.reason}`];
  });
  L.push(table(['Rule', 'Sev', 'Status', 'qa-ci DV', 'Found', 'Rows', 'Baseline', 'Expires', 'WP', 'Breakdown / reason'], rows));
  L.push('');
  L.push('### Rule definitions and the specialist baselines they are compared with');
  L.push('');
  L.push(table(['Rule', 'Check', 'Specialist baseline (chapter 13 / DI 6)', 'Note'], [...results.values()].map((r) => [r.rule.id, r.rule.title, r.rule.spec_baseline || '-', r.rule.note || r.rule.blocked_by || ''])));
  L.push('');
  L.push('## 3. Reproduction of the chapter-13 section 2 numbers');
  L.push('');
  const okN = sec2.filter((x) => x.ok).length;
  L.push(`${okN} of ${sec2.length} measurements reproduce the chapter's number exactly. Differences are listed with their cause.`);
  L.push('');
  L.push(table(['Group', 'Fact', 'Expected (chapter)', 'Measured', 'Match', 'Note'], sec2.map((x) => [x.group, x.fact, x.expected, x.measured, x.ok ? 'yes' : 'NO', x.note || ''])));
  L.push('');
  L.push('### Where this suite differs from the specialist numbers (and why)');
  L.push('');
  const diffs = [
    ['median rows per populated tick', 'true median of 188 ticks is 6.5; the chapter\'s 6 is the lower median'],
    ['" -- " count', `the nine field groups the data-integrity report names add to 1,590 by its own figures (stated total 1,591); this suite reproduces 1,590. Rule X001 uses a wider, defined scope (all published prose plus successions, casualty notes and every commander fate): ${n(results.get('X001').violations.length)} occurrences`],
    ['S008 loose tick ranges', `the specialist counted 3 (ticks101_225, ticks601_675, ticks451_520); a fourth file, placements_day1_ticks51_100 (declared 51-100, first row at tick 52), is also loose: ${results.get('S008').violations.filter((v) => v.kind === 'tick_range_loose').length} measured`],
    ['R002 wrong side', 'exactly 10 ids (state code contradicts prefix, twin exists); brigade/division-shaped ids that exist on both sides (U-I-2-3, C-CAV-2-1..3) are NOT flipped'],
    ['R011 dual meaning', `the strict note-versus-commander rule finds ${new Set(results.get('R011').violations.map((v) => v.data.unit_id)).size} ids / ${results.get('R011').violations.length} rows (same kind, target exists); the specialist heuristic found 28 ids / 44 rows. The collision table in data-src/build/id_collisions.json widens the definition (a note that BEGINS with another formation's name at any level, parent/child cameos excluded, plus rows whose strength exceeds twice the record's) and reaches 28 ids, the audit's count; the membership was not diffed because the audit's CSV is not in the repository.`],
    ['G003 speed caps', `${extras.g003_linear_over_cap} segments over the DI-01 lenient caps on the 5-minute clock and ${extras.g003_warped_over_cap ?? 'n/a'} on the unsigned warped-clock proposal; the specialist quotes 6 and 20 with caps that were not published in full`],
    ['C004 coverage', '248 real regiments + 66 batteries; the specialist 250 counts the alias stub and the horse battery filed as a regiment'],
    ['N005 roll-ups', 'interim tolerances (brigades 10 %, divisions/corps exact) reproduce the specialist counts within one record'],
  ];
  L.push(table(['Item', 'Difference'], diffs));
  L.push('');
  L.push('## 4. Skipped and partial rules');
  L.push('');
  L.push(table(['Rule', 'Status', 'Why'], [...skipped.map((r) => [r.rule.id, 'SKIPPED', r.reason]), ...partial.map((r) => [r.rule.id, 'PARTIAL', r.rule.note || ''])]));
  L.push('');
  L.push('## 5. Additional measurements');
  L.push('');
  L.push(table(['Measure', 'Value'], [
    ['G003 over caps, 5-minute clock / warped proposal', `${extras.g003_linear_over_cap} / ${extras.g003_warped_over_cap ?? 'n/a'} (of ${extras.g003_segments_measured} segments >= 50 m)`],
    ['moving segments (> 250 m) / of which > 120 clock-min on the warped proposal', `${extras.moving_segments} / ${extras.moving_segments_over_120_minutes_warped ?? 'n/a'} (chapter: 590 / 297)`],
    ['moving gaps > 10 ticks / > 30 ticks', `${extras.moving_gaps_over_10_ticks} / ${extras.moving_gaps_over_30_ticks} (DI: 351 / 217)`],
    ['G004 stacked groups on raw rows / on merged rows', `${extras.stacked_raw_groups} groups, ${extras.stacked_raw_units} units / ${results.get('G004').violations.length} groups, ${rowsOf(results.get('G004').violations)} units (DI: 48 / 96 and 39 / 78)`],
    ['same-tick unit pairs closer than 15 m (merged rows)', extras.same_tick_pairs_under_15m],
    ['regiment records without casualty_percentage / commander / parent_corps_id / days_engaged', `${extras.completeness.no_casualty_percentage} / ${extras.completeness.no_commander} / ${extras.completeness.no_parent_corps_id} / ${extras.completeness.empty_days_engaged} (of ${extras.completeness.regiments} regiments; chapter counts 467 records: 222 / 27 / 22 / 37)`],
    ['regiments with key_action under 40 chars / flag_notes records / non-state "state" values', `${extras.completeness.short_key_action} / ${extras.completeness.flag_notes} / ${extras.completeness.non_state_values} (chapter: 169 / 60 / 16)`],
    ['string leaves in served data', n(extras.all_strings)],
  ]));
  L.push('');
  L.push('## 6. Provenance coverage (rule P001)');
  L.push('');
  L.push(table(['Record class', 'Records', 'With a per-record source string', '%'], cov.map((c) => [c.name, n(c.total), n(c.sourced), c.total ? (100 * c.sourced / c.total).toFixed(1) : '-'])));
  const tot = cov.reduce((a, c) => a + c.total, 0), src = cov.reduce((a, c) => a + c.sourced, 0);
  L.push('');
  L.push(`Overall ${n(src)} of ${n(tot)} records (${(100 * src / tot).toFixed(1)} %). "Documented" positions: 0 (no anchor carries a \`basis\`). None of these source strings resolves in a registry (there is none): they are claims, never verified (chapter 13 section 2.4).`);
  L.push('');
  L.push('## 7. ID crosswalk summary (generated by tools/data/unit_registry.mjs)');
  L.push('');
  L.push(table(['Measure', 'Value'], [
    ['unresolved placed ids / rows', `${crosswalk.counts.unresolved_ids} / ${crosswalk.counts.rows}`],
    ['proposal confidence high / medium / low / none', `${crosswalk.counts.by_confidence.high} / ${crosswalk.counts.by_confidence.medium} / ${crosswalk.counts.by_confidence.low} / ${crosswalk.counts.by_confidence.none}`],
    ['share high, share high+medium', `${(100 * crosswalk.counts.auto_high_share).toFixed(1)} % / ${(100 * crosswalk.counts.auto_high_or_medium_share).toFixed(1)} % (the audit\'s auto-match figure is 87.6 %; this engine is stricter and marks every non-high row needs_historian)`],
    ['rows needing the historian', crosswalk.counts.needs_historian],
    ['registry: units / regiments / batteries', `${registry.census.total} / ${registry.census.regiments} / ${registry.census.batteries}`],
    ['registry: units needing the historian (flags)', registry.census.needs_historian],
    ['dual-meaning ids (an id used for a second formation) / rows re-keyable / strength-only suspects', `${collisions.length} / ${collisions.reduce((a, c) => a + c.rows.length, 0)} / ${collisions.filter((c) => !c.rows.length).length} (the audit: 28 ids / 44 rows; same count, membership not diffed: the audit\'s CSV is not in the repository)`],
  ]));
  L.push('');
  L.push(table(['Rule', 'Ids'], Object.entries(crosswalk.counts.by_rule).map(([k, v]) => [k, v])));
  L.push('');
  L.push('## 8. Retired literals still printed (rule F001)');
  L.push('');
  const hits = retiredLiteralHits(ctx);
  const byId = new Map();
  for (const h of hits) { if (!byId.has(h.id)) byId.set(h.id, []); byId.get(h.id).push(`${h.where}:${h.line}`); }
  L.push(table(['Literal', 'Occurrences', 'Locations'], [...byId].map(([id, locs]) => [id, locs.length, locs.slice(0, 12).join(', ') + (locs.length > 12 ? ` ... (+${locs.length - 12})` : '')])));
  L.push('');
  L.push('## 9. Baseline size');
  L.push('');
  const fp = Object.values(baseline.rules).reduce((a, r) => a + r.count, 0);
  L.push(`${Object.keys(baseline.rules).length} rules carry ${n(fp)} fingerprints; expiry per family is a proposal (schema/refs/text 2027-01-31, numbers/facts 2027-03-31, coverage/geometry/time/provenance 2027-06-30) to be aligned with the roadmap gates.`);
  L.push('');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, L.join('\n') + '\n', 'utf8');

  // machine-readable public report (chapter 13 WP-DATA-03: % sourced, % documented, schematic count)
  const schematic = ctx.rows.filter((r) => r.tick === 1);
  const lngCount = new Map();
  for (const r of schematic) lngCount.set(r.lng, (lngCount.get(r.lng) || 0) + 1);
  const dq = {
    schema: 'gtbg/data-quality-report/1',
    status: 'CANDIDATE (not published; /method is chapter 11)',
    data_version: treeInfo.data_version,
    data_content_sha256: treeInfo.content_sha256,
    rules: [...results.values()].map((r) => ({ id: r.rule.id, sev: r.rule.sev, status: r.ran ? r.rule.status : 'skipped', found: r.ran ? r.violations.length : null, rows: r.ran ? rowsOf(r.violations) : null })),
    provenance: { records: tot, with_source_string: src, percent_with_source_string: Number((100 * src / tot).toFixed(2)), percent_documented: 0, note: 'no source resolves in a registry; no anchor carries basis' },
    schematic: { tick1_rows: schematic.length, tick1_rows_on_shared_longitudes: schematic.filter((r) => lngCount.get(r.lng) > 1).length, rows_under_4_decimals: results.get('G002').violations.length },
  };
  fs.writeFileSync(path.join(REPO_ROOT, 'data-src', 'build', 'data-quality-report.json'), prettyJson(dq));
}
