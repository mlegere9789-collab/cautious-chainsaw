#!/usr/bin/env python3
"""List every backticked token of GATE-SPEC-A.md that looks like a repository path and say whether it exists.
Resolution order: as written from the repository root, then under docs/battle-theatre/, GOVERNANCE/, GOVERNANCE/gate_results/, app/, tools/bt/.
A token with a glob star is tested with glob. Reads files only. Usage: python3 -I check_paths.py [path-to-spec]"""
import re, sys, os, glob, json
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from plan_lib import SPEC, ROOT, GOV
doc = sys.argv[1] if len(sys.argv) > 1 else SPEC
text = open(doc, encoding='utf-8').read()
text = re.sub(r'```.*?```', '', text, flags=re.S)
bases = ['', 'docs/battle-theatre', 'docs/battle-theatre/GOVERNANCE', 'docs/battle-theatre/GOVERNANCE/gate_results', 'docs/battle-theatre/app', 'tools/bt', 'docs/battle-theatre/app/data', 'docs/battle-theatre/app/tests', 'docs/battle-theatre/app/src',
         'docs/battle-theatre/structures', 'docs/battle-theatre/history', 'docs/battle-theatre/kit', 'docs/battle-theatre/GOVERNANCE/library', 'docs/battle-theatre/GOVERNANCE/decisions', 'docs/battle-theatre/app/src/ui', 'docs/battle-theatre/app/docs',
         'docs/battle-theatre/GOVERNANCE/realizations', 'tools/bt/photomatch', 'docs/battle-theatre/kit/evidence', 'docs/battle-theatre/library', 'docs/battle-theatre/GOVERNANCE/gate_results/spec-a-evidence']
# Paths that the spec itself names as absent, announced or generated by a run (never inputs of today); a token in this set is not an error.
ANNOUNCED = {'kit/verified_oob.json', 'kit/verified_batteries.json', 'GOVERNANCE/gate_results/thresholds.json', 'GOVERNANCE/gate_results/Qnn.json', 'Qnn.prev.json', 'OAnn.json', 'RC-Rnn.json',
             'GOVERNANCE/gate_results/latest/<gate>.json', 'GOVERNANCE/final-passes/pass-N.md', 'gate_results/evidence/Qnn/', 'GOVERNANCE/register/search_logs/<EG id>.json', 'n/a',
             'spec-a-evidence/library_words.py', 'thresholds.json', 'Qnn.json', 'tools/bt/gates/', 'arrivals.json', 'candidates.json', 'not_on_field.json', 'extensions.mjs', 'gait-sources.json'}
seen = {}
for m in re.finditer(r'`([^`\n]{3,120})`', text):
    tok = m.group(1).strip()
    if ' ' in tok and not tok.endswith('*'): continue
    if not re.search(r'[A-Za-z0-9_\-]/[A-Za-z0-9_\-*]|\.(?:json|jsonl|mjs|py|md|txt|sh|js)$', tok): continue
    if tok.startswith(('http', '--', '<')) or re.match(r'^[A-Z]{2,}\d', tok): continue
    seen[tok] = seen.get(tok, 0) + 1
missing, ok, announced = [], 0, []
for tok in sorted(seen):
    t = tok.split('::')[0].split(' ')[0].rstrip(',.;:')
    t = re.sub(r'\{([^{},]+),[^{}]*\}', r'\1', t)      # positions_{A,B,C,D,E}.jsonl -> positions_A.jsonl (the first alternative stands for the set)
    found = False
    for b in bases:
        p = os.path.join(ROOT, b, t)
        if '*' in t or '<' in t:
            if glob.glob(re.sub(r'<[^>]*>', '*', p)): found = True; break
        elif os.path.exists(p): found = True; break
    if found: ok += 1
    elif tok in ANNOUNCED or t in ANNOUNCED: announced.append(tok)
    else: missing.append(tok)
print(json.dumps({'path_like_tokens': len(seen), 'exist': ok, 'announced_absent_or_generated': len(announced), 'not_found': len(missing)}))
for tok in missing: print('NOT FOUND:', tok)
