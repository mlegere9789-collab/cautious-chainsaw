#!/usr/bin/env python3
"""Write ws-web/nps/SUMMARY.md: counts of the extracts by topic, state use, tier and source, the register of conflicts the
reports themselves carry, the list of features that must NOT be drawn in the July 1863 scene (use none), the extracts that are
modern or rebuilt states (use indirect), and the sources not yet read for extracts with the reason.
Run with python3 -I (after build_extracts.py and build_sources.py).
"""
import collections, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
NPS = os.path.dirname(HERE)
rows = [json.loads(l) for l in open(os.path.join(NPS, 'extracts', 'extracts.jsonl'), encoding='utf-8') if l.strip()]
sources = {s['id']: s for s in json.load(open(os.path.join(NPS, 'sources.json')))['sources']}
meta = json.load(open(os.path.join(NPS, 'source_meta.json')))['items']
NOTREAD = json.load(open(os.path.join(NPS, 'not_extracted.json')))['items'] if os.path.exists(os.path.join(NPS, 'not_extracted.json')) else {}


def tab(counter, head):
    out = ['| %s | n |' % head, '|---|---|']
    for k, v in sorted(counter.items(), key=lambda kv: -kv[1]):
        out.append('| %s | %d |' % (k, v))
    return '\n'.join(out)


L = ['# Extract summary (generated by scripts/summary.py; do not edit)', '',
     '%d extracts from %d of %d sources. Every quote was matched letter for letter against the saved text by `scripts/build_extracts.py` and again by `scripts/verify_extracts.py`.' % (len(rows), len({r['source_id'] for r in rows}), len(sources)), '',
     '## By topic', '', tab(collections.Counter(r['topic'] for r in rows), 'topic'), '',
     '## By use for the July 1863 scene', '',
     '`direct` = the passage states an 1863 (or earlier, still standing) condition; `indirect` = a later, modern, rebuilt or replanted state, usable only as a marked inference and never as an 1863 profile; `none` = a feature that did not exist in July 1863 (never drawn in the 1863 scene).', '',
     tab(collections.Counter(r['use_for_1863'] for r in rows), 'use'), '',
     '## By tier proposed', '', tab(collections.Counter(r['tier_proposed'] for r in rows), 'tier'), '',
     '## By quote mode', '', tab(collections.Counter(r.get('quote_mode', 'anchors') for r in rows), 'mode'), '',
     '## By source', '', tab(collections.Counter(r['source_id'] for r in rows), 'source'), '']
conf = [r for r in rows if r['source_certainty'] == 'conflict']
L += ['## Conflicts carried by the reports themselves (%d)' % len(conf), '',
      'Each is a passage in which the report states two readings or contradicts another passage; carry every reading as a selectable scenario.', '']
for r in conf:
    L.append('- `%s` %s (%s p. %s): %s' % (r['xid'], r['feature'], r['source_id'], r['printed_page'] or 'PDF %d' % r['pdf_page'], r['claim']))
L += ['', '## Features placed after July 1863: never drawn in the 1863 scene (use none, %d)' % sum(1 for r in rows if r['use_for_1863'] == 'none'), '']
for r in sorted((r for r in rows if r['use_for_1863'] == 'none'), key=lambda r: (r['state_date'], r['xid'])):
    L.append('- %s: %s (`%s`)' % (r['state_date'], r['feature'], r['xid']))
L += ['', '## Not yet read for extracts, or read and not usable (reason)', '']
for sid, s in sources.items():
    if not any(r['source_id'] == sid for r in rows):
        L.append('- `%s` (%s pages, %s with text): %s' % (sid, s['pages'], s['pages_with_text'], NOTREAD.get(sid, 'not yet read for extracts')))
L += ['', '## Read in part: what is still owed for sources that have extracts', '']
have = {r['source_id'] for r in rows}
for sid, s in sources.items():
    if sid in have and meta.get(sid, {}).get('owed'):
        L.append('- `%s`: %s' % (sid, meta[sid]['owed']))
L += ['', '## Rights notes (sources not authored by Service staff, or whose status is not established)', '']
for sid, s in sources.items():
    if s.get('rights_note'):
        L.append('- `%s`: %s. %s' % (sid, s['rights_basis'], s['rights_note']))
open(os.path.join(NPS, 'SUMMARY.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('SUMMARY.md written')
