// Builds app/data/cavalry-horses.json (riders and horses per drawn cavalry unit as ranges with their basis, the horse-loss and dismount models with their sources and tiers, the batteries' horse losses, the gaps) and,
// with --register, the proposed register entries GOVERNANCE/horde/ws10-cavalry/proposed-register/EG-CAV-0x.md. Deterministic: no clock, no randomness.
//   node docs/battle-theatre/app/tools/build-cavalry-horses.mjs [--register]
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { nodeWorld } from '../tests/node-world.mjs';
import { loadRawFromDisk, terrainMeta } from './history-report.mjs';
import { createRealHistory } from '../src/history/real.mjs';
import * as C from '../src/history/cavalry.mjs';
const here = path.dirname(fileURLToPath(import.meta.url)), APP = path.resolve(here, '..'), BT = path.resolve(APP, '..');

export async function build() {
  const raw = loadRawFromDisk(), TM = terrainMeta(), L = createRealHistory({ raw, T: TM, helpers: { civilDawn: m => m + 4 * 60 + 3 } }); void nodeWorld;
  const units = {}, undrawn = [];
  for (const u of L.units) if (u.arm === 'cavalry' && u.level !== 'brigade' && u.level !== 'division') {
    const n = u.strength.drawn || 0; if (!n) { undrawn.push(u.id); continue; }
    const rec = C.dismountRecord(u.id), share = rec ? C.dismountShare(rec) : null;
    units[u.id] = { ...C.horseRange(n), dismount: rec ? { record: rec.id, share, counts: share ? C.dismountCounts(n, share) : null, windows_min: C.dismountWindows(rec, u.casualties && u.casualties.windows) } : null };
  }
  return {
    schema: 'cavalry-horses-1',
    note: 'Riders, horses, horse casualties, dismounted fights and draught-horse losses of the batteries. Generated by tools/build-cavalry-horses.mjs from src/history/cavalry.mjs and the real history layer; nothing here is hand-edited. Every number carries its tier; the gaps are in gaps[] and in GOVERNANCE/horde/ws10-cavalry/proposed-register.',
    tier_of_the_model: C.TIER,
    horse_observations: C.HORSE_OBSERVATIONS, mounted_share: C.MOUNTED_SHARE, horse_loss: C.HORSE_LOSS, holder: C.HOLDER, led_horses: C.LED, dismounts: C.DISMOUNTS, battery_horse_losses: C.BATTERY_HORSE_LOSSES,
    units, undrawn_cavalry_units: undrawn, gaps: C.GAPS,
  };
}
const cell = s => String(s).replace(/\|/g, '/');
export function registerEntry(g) {
  return `# ws10-${g.id}: ${g.title}

| Field | Content |
|---|---|
| ID | ws10-${g.id} |
| Requirement IDs | R01, R03 (horses, riders and the dismounted fight are part of the units and the battle as drawn); PDF B.6.14, B.6.15 |
| Category | evidence missing |
| Description | ${cell(g.text)} |
| Why literal 100% is not possible or blocked | No non-lead source acquired states the missing quantity; see the description. |
| Evidence searched | kit/cavalry_units.json (horses, strengths, behaviour_states), history/positions ledgers A, D, E (claims named in app/data/cavalry-horses.json), kit/artillery_batteries.json losses. |
| Autonomous substitute applied | The model in app/src/history/cavalry.mjs, marked ${g.tier} on the unit card (section Riders and horses) and in app/data/cavalry-horses.json. |
| Strongest evidence-based reconstruction | As stated in the description; no value is promoted above its tier. |
| Confidence tier | ${g.tier} |
| Product marking | Unit card section "Riders and horses": range, basis, tier pill and gap id. |
| Review status | internal review only (DEC-006: no public review label) |
| Owner decision requested | Confirm or replace the model parameter named in the description; read the OR page or the regimental history that would settle it. |
| Status | open (proposed by workstream ws10; not yet in register/) |
| Owner decision and date | (filled only from the Decision Log) |
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const d = await build(); fs.writeFileSync(path.join(APP, 'data/cavalry-horses.json'), JSON.stringify(d, null, 1) + '\n'); console.log('cavalry-horses.json: ' + Object.keys(d.units).length + ' drawn units, ' + d.undrawn_cavalry_units.length + ' undrawn');
  if (process.argv.includes('--register')) { const dir = path.join(BT, 'GOVERNANCE/horde/ws10-cavalry/proposed-register'); fs.mkdirSync(dir, { recursive: true }); for (const g of C.GAPS) fs.writeFileSync(path.join(dir, `ws10-${g.id}.md`), registerEntry(g)); console.log('register entries: ' + C.GAPS.length); }
}
