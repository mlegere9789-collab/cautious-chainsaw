// Node tests of the North Carolina Confederate roster files (work item conf-nc): the 41 unit files under rosters/data2/confederate/nc, their flag files, the pointer file,
// the two source ledgers (Moore 1882, Clark 1901) and the Clark notes.
//   node --test docs/battle-theatre/app/tests/roster-conf-nc.test.mjs
// No browser, no network, no source text: the checks that need the pinned OCR text (every name and every remark found at its recorded offset, the page of the leaf, the quotation of
// every Clark note found at its place) are made by the builders before a file is written and again by rosters/pipeline2/verify_unit.py and nc_clark.py --check; here the files are
// checked against themselves and against the pointer file: shape of every line, the header count, offsets that only grow, printed pages inside the register of the volume,
// the flag file joined to the unit file by its hash, indexes in range, no row both "on the rolls" and "not on the rolls", size and sha256 of every file equal to the pointer file,
// rights basis only where the year allows it, the statistics file equal to the files, the structure of every Clark note, and that no printed name, remark or note of ours mentions
// how the data was made.
import test from 'node:test'; import assert from 'node:assert/strict'; import fs from 'node:fs'; import path from 'node:path'; import zlib from 'node:zlib'; import crypto from 'node:crypto'; import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url)), BT = path.resolve(HERE, '..', '..'), ROSTERS = path.join(BT, 'rosters'), REPO = path.resolve(BT, '..', '..');
const GOV = path.join(BT, 'GOVERNANCE', 'horde', 'ws-rosters', 'conf-nc');
const CO_CODES = new Set(['', 'A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'K', 'L', 'M', 'N', 'O', 'P', 'Q', 'R', 'S', 'T', 'FS', 'NCS', 'BAND', 'UNAS']);
const FLAG_CODES = ['N', 'H', 'C', 'R', 'Y', 'G', 'M', 'W'];
const NOTE_KINDS = new Set(['present_for_duty', 'taken_into_action', 'remaining_after', 'casualties', 'strength_other', 'identification']);
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const inRepo = (p) => path.join(REPO, p);
const pointer = readJson(path.join(ROSTERS, 'sources', 'conf-nc.json'));
const stats = readJson(path.join(GOV, 'stats.json'));
const moore = readJson(path.join(ROSTERS, 'data2', 'sources', 'NC-MOORE-1882.json'));
const clark = readJson(path.join(ROSTERS, 'data2', 'sources', 'NC-CLARK-1901.json'));
const UNITS = pointer.unit_files, UNIT_IDS = new Set(UNITS.map((u) => u.unit));
const PROCESS_WORDS = /\b(?:Anthropic|Claude Code|subagents?|LLM|language model|artificial intelligence|machine[- ]generated|generated by)\b|pipeline2|\.py\b/i;

function loadUnit(u) {
  const gz = fs.readFileSync(inRepo(u.path)), raw = zlib.gunzipSync(gz).toString('utf8');
  assert.ok(raw.endsWith('\n'), 'the file ends with a newline');
  const lines = raw.slice(0, -1).split('\n').map((l) => JSON.parse(l));
  const fgz = fs.readFileSync(inRepo(u.flags_path)), flags = JSON.parse(zlib.gunzipSync(fgz).toString('utf8'));
  return { gz, raw, lines, fgz, flags };
}

test('conf-nc: the pointer file lists the 41 units (33 infantry, 4 cavalry, 4 batteries), each with the two files of the unit', () => {
  assert.equal(pointer.format, 'roster2-sources-pointer/1'); assert.equal(pointer.work_item, 'conf-nc');
  assert.equal(UNITS.length, 41); assert.equal(UNIT_IDS.size, 41);
  const arm = { infantry: 0, cavalry: 0, artillery: 0, other: 0 };
  for (const u of UNITS) {
    assert.match(u.unit, /^c-nc-/); assert.ok(u.rows > 0); assert.equal(u.text_ids.length, 1); assert.match(u.text_ids[0], /^NC-MOORE-1882\.[1-4](?:~b)?$/);
    for (const p of [u.path, u.flags_path]) assert.ok(fs.existsSync(inRepo(p)), p);
    arm[/infantry|battalion/.test(u.unit) ? 'infantry' : /cavalry/.test(u.unit) ? 'cavalry' : /artillery/.test(u.unit) ? 'artillery' : 'other']++;
  }
  assert.deepEqual(arm, { infantry: 33, cavalry: 4, artillery: 4, other: 0 });
});

for (const u of UNITS) {
  const L = loadUnit(u), header = L.lines[0], rows = L.lines.filter(Array.isArray), short = u.path.split('/').pop().replace('.jsonl.gz', '');

  test(`${short}: header, segment and row count`, () => {
    assert.deepEqual({ f: header.f, u: header.u, army: header.army, st: header.st, name: header.name }, { f: 'roster2/2', u: u.unit, army: 'confederate', st: 'nc', name: u.designation });
    assert.equal(header.n, rows.length); assert.equal(rows.length, u.rows);
    const segs = L.lines.filter((x) => !Array.isArray(x) && x.s);
    assert.equal(segs.length, 1); assert.deepEqual(segs[0], { s: 'NC-MOORE-1882', v: u.text_ids[0].slice('NC-MOORE-1882.'.length)[0], t: u.text_ids[0], lay: 'flow' });
  });

  test(`${short}: every line has the shape of roster2/2, offsets grow, pages and companies are plausible`, () => {
    let first = true, co = '', pg = null, names = 0, last = null;
    for (const x of L.lines.slice(1)) {
      if (Array.isArray(x)) {
        assert.ok([2, 3, 5].includes(x.length), 'row length'); assert.equal(typeof x[0], 'number'); assert.equal(typeof x[1], 'string'); assert.ok(x[1].length > 0, 'a printed name');
        if (x.length >= 3) assert.equal(typeof x[2], 'string');
        if (x.length === 5) { assert.equal(typeof x[3], 'string'); assert.ok(x[3].length > 0); assert.ok(Number.isInteger(x[4]), 'offset of the remarks from the name'); }
        if (!first) assert.ok(x[0] > 0, 'offsets only grow'); first = false; names++;
        assert.ok(CO_CODES.has(co), 'company code ' + co);
        if (pg !== null) assert.ok(Number.isInteger(pg) && pg >= 1 && pg <= 1400, 'printed page ' + pg + ' of ' + x[1]);
        assert.ok(!/\n/.test(x[1]) && !/\s{2,}/.test(x[1]) && x[1] === x[1].trim(), 'name tokens joined by single blanks');
        assert.ok(!/^\^/.test(x[2] || ''), 'a rank never begins with the marker of a carried heading');
        last = x;
      } else if (!x.s) { assert.ok(Object.keys(x).every((k) => ['co', 'pg', 'rk'].includes(k))); if ('co' in x) co = x.co; if ('pg' in x) pg = x.pg; }
    }
    assert.equal(names, u.rows); assert.ok(last);
  });

  test(`${short}: flag file is joined to the unit file and its indexes are in range`, () => {
    const f = L.flags, n = rows.length;
    assert.equal(f.f, 'roster2-flags/1'); assert.equal(f.u, u.unit); assert.equal(f.n, n);
    assert.equal(f.unit_file_raw_lines_sha256, sha(Buffer.from(L.raw, 'utf8')));
    const inRange = (i) => Number.isInteger(i) && i >= 0 && i < n;
    assert.ok(f.ocr_uncertain.every(inRange)); assert.deepEqual([...f.ocr_uncertain], [...f.ocr_uncertain].sort((a, b) => a - b));
    for (const [code, list] of Object.entries(f.rows)) { assert.ok(FLAG_CODES.includes(code) && code in f.codes, 'code ' + code); assert.ok(list.every(inRange)); }
    const union = new Set(Object.values(f.rows).flat()); assert.equal(union.size, f.ocr_uncertain.length); assert.ok(f.ocr_uncertain.every((i) => union.has(i)));
    for (const k of ['names_gettysburg', 'gettysburg_dated']) { assert.ok(f[k].every(inRange)); assert.deepEqual([...f[k]], [...f[k]].sort((a, b) => a - b)); }
    const gd = new Set(f.names_gettysburg); assert.ok(f.gettysburg_dated.every((i) => gd.has(i)), 'a row with a July 1863 date in its Gettysburg clause names Gettysburg');
    const yes = f.on_rolls_july_1863.yes, no = f.on_rolls_july_1863.no, basis = f.on_rolls_july_1863.basis;
    for (const [i, b] of [...yes, ...no]) { assert.ok(inRange(i)); assert.ok(Number.isInteger(b) && b >= 0 && b < basis.length); }
    const y = new Set(yes.map((p) => p[0])); assert.ok(no.every((p) => !y.has(p[0])), 'no row is both on and off the rolls');
    assert.equal(new Set(yes.map((p) => p[0])).size, yes.length); assert.equal(new Set(no.map((p) => p[0])).size, no.length);
    assert.equal(f.normalised_names.length, n);
    for (const [, b] of yes) assert.match(basis[b], /^enl /); for (const [, b] of no) assert.match(basis[b], /^(?:separation before|start after) /);
    for (const list of Object.values(f.head_kinds)) assert.ok(list.every(inRange));
    for (const s of f.company_inferred) { assert.ok(inRange(s.first_row) && inRange(s.last_row) && s.first_row <= s.last_row); assert.equal(s.n_rows, s.last_row - s.first_row + 1); assert.ok(f.rows.C.includes(s.first_row)); }
  });

  test(`${short}: pointer file records this file's size and sha256`, () => {
    assert.equal(u.file_bytes, L.gz.length); assert.equal(u.file_sha256, sha(L.gz)); assert.equal(u.raw_lines_sha256, sha(Buffer.from(L.raw, 'utf8')));
    assert.equal(u.flags_bytes, L.fgz.length); assert.equal(u.flags_sha256, sha(L.fgz));
    const st = stats.units[u.unit]; assert.equal(st.lines, rows.length); assert.equal(st.sha256_raw, u.raw_lines_sha256); assert.equal(st.gz_bytes, L.gz.length); assert.equal(st.ocr_uncertain, L.flags.ocr_uncertain.length);
    assert.equal(st.names_gettysburg, L.flags.names_gettysburg.length); assert.equal(st.gettysburg_dated, L.flags.gettysburg_dated.length);
    assert.deepEqual(st.on_rolls, { yes: L.flags.on_rolls_july_1863.yes.length, no: L.flags.on_rolls_july_1863.no.length, unknown: rows.length - L.flags.on_rolls_july_1863.yes.length - L.flags.on_rolls_july_1863.no.length });
  });

  test(`${short}: nothing in a printed name or remark says how the data was made`, () => {
    assert.ok(!PROCESS_WORDS.test(L.raw)); assert.ok(!PROCESS_WORDS.test(JSON.stringify(L.flags)));
  });
}

test('conf-nc: the sources of the pointer file are the 8 pinned texts of Moore (1882) and the 10 of Clark (1901), each with a hash, and the rights basis only where the year allows it', () => {
  assert.equal(pointer.sources.length, 18);
  const ids = new Set(pointer.sources.map((s) => s.text_id)); assert.equal(ids.size, 18);
  for (const u of UNITS) assert.ok(ids.has(u.text_ids[0]), 'the text of ' + u.unit + ' is a source of the pointer file');
  for (const s of pointer.sources) {
    assert.ok(s.rights.basis === 'public domain (United States publication before 1929)' ? s.year < 1929 : true); assert.ok([1882, 1901].includes(s.year));
    assert.ok(s.files.length >= 3); for (const f of s.files) { assert.match(f.sha256, /^[0-9a-f]{64}$/); assert.ok(f.bytes > 0); assert.match(f.url, /^https:\/\/archive\.org\//); }
    const led = (s.source_id === 'NC-MOORE-1882' ? moore : clark).texts[s.text_id]; assert.ok(led, s.text_id + ' is pinned in its ledger');
    assert.equal(led.files.text.sha256, s.sha256); assert.equal(led.files.text.bytes, s.bytes); assert.equal(led.ia_identifier, s.identifier);
    assert.ok(s.rights.evidence.imprint_quote && s.rights.evidence.imprint_quote.length > 8, 'the imprint is quoted');
  }
  assert.equal(Object.keys(moore.texts).length, 8); assert.equal(Object.keys(clark.texts).length, 10);
  for (const x of pointer.not_used || []) assert.ok(!('rights' in x) || x.rights.basis !== 'public domain (United States publication before 1929)' || x.year < 1929);
});

test('conf-nc: the Clark notes are notes of the ledger and never rows, each with a quotation, its place, its units and its tier', () => {
  assert.equal(clark.notes_format, 'roster2-notes/1'); assert.equal(pointer.notes_file.count, clark.notes.length); assert.equal(pointer.notes_file.member, 'notes');
  assert.equal(pointer.notes_file.path, 'docs/battle-theatre/rosters/data2/sources/NC-CLARK-1901.json');
  assert.equal(stats.totals.clark_notes, clark.notes.length);
  const ids = new Set(); const perUnit = {}; const perKind = {};
  for (const n of clark.notes) {
    assert.match(n.id, /^CL-\d{3}$/); assert.ok(!ids.has(n.id), 'note ids are unique'); ids.add(n.id);
    assert.ok(Array.isArray(n.units) && n.units.length >= 1); for (const k of n.units) { assert.ok(UNIT_IDS.has(k), k); perUnit[k] = (perUnit[k] || 0) + 1; }
    assert.ok(NOTE_KINDS.has(n.kind), n.kind); perKind[n.kind] = (perKind[n.kind] || 0) + 1;
    for (const k of ['subject', 'when', 'claim', 'quote', 'chapter', 'tier']) assert.ok(typeof n[k] === 'string' && n[k].length > 0, `${n.id}.${k}`);
    assert.match(n.tier, /^documented: /); assert.ok(n.t in clark.texts, n.t);
    assert.ok(Number.isInteger(n.off) && Number.isInteger(n.end) && n.end > n.off, 'the quotation has a place in the pinned text');
    assert.ok(Number.isInteger(n.leaf) && n.leaf >= 0); assert.ok(n.pg === null || (Number.isInteger(n.pg) && n.pg >= 1));
    assert.ok(Array.isArray(n.figures)); for (const f of n.figures) { assert.equal(typeof f.printed, 'string'); assert.ok(f.printed.length > 0); assert.ok(Number.isInteger(f.value) || f.value === null); assert.equal(typeof f.what, 'string'); }
    assert.ok(n.strength_figure === null || Number.isInteger(n.strength_figure));
    const ss = n.second_scan; assert.ok(ss && typeof ss.found === 'boolean' && (ss.found ? typeof ss.agrees === 'boolean' : ss.agrees === null), n.id + ' second scan'); assert.notEqual(ss.t, n.t); assert.equal(ss.t.replace(/~b$/, ''), n.t.replace(/~b$/, ''));
    if (ss.found) { assert.ok(Number.isInteger(ss.off) && Number.isInteger(ss.end)); assert.ok(ss.quote.length > 0); } else assert.ok(typeof ss.reason === 'string' && ss.reason.length > 0);
    if (n.page_image_check) { const p = n.page_image_check; assert.ok(['viewed', 'tesseract'].includes(p.how)); assert.ok(Number.isInteger(p.leaf) && typeof p.result === 'string' && p.result.length > 0); assert.equal(typeof p.reads, 'object'); }
    assert.ok(!PROCESS_WORDS.test([n.subject, n.when, n.claim, n.chapter, n.tier].join('\n')), n.id + ' says how it was made');
  }
  assert.deepEqual(Object.fromEntries(Object.entries(perKind).sort()), Object.fromEntries(Object.entries(stats.clark_kinds).sort()));
  assert.equal(Object.keys(clark.notes_units).length, 41);
  for (const [k, v] of Object.entries(clark.notes_units)) { assert.ok(UNIT_IDS.has(k)); assert.equal(v.notes, perUnit[k] || 0); assert.equal(Object.values(v.notes_by_kind || {}).reduce((a, b) => a + b, 0), v.notes); }
  assert.equal(Object.keys(clark.notes_units).filter((k) => clark.notes_units[k].notes > 0).length, stats.totals.clark_units_with_notes);
  assert.ok(clark.notes.some((n) => n.strength_figure === 885), 'the present-for-duty total of the 26th Regiment (885, Underwood) is a note');
  assert.ok(!PROCESS_WORDS.test(clark.notes_scope) && !PROCESS_WORDS.test(clark.notes_format));
});

test('conf-nc: the totals of the statistics file are the sums of the unit files', () => {
  assert.equal(stats.format, 'conf-nc-stats/1'); assert.deepEqual(stats.units_without_file, []);
  assert.equal(Object.keys(stats.units).length, 41);
  let lines = 0, gz = 0, unc = 0, yes = 0, no = 0, gett = 0; const codes = Object.fromEntries(FLAG_CODES.map((c) => [c, 0]));
  for (const u of UNITS) { const L = loadUnit(u); lines += u.rows; gz += u.file_bytes; unc += L.flags.ocr_uncertain.length; yes += L.flags.on_rolls_july_1863.yes.length; no += L.flags.on_rolls_july_1863.no.length; gett += L.flags.names_gettysburg.length; for (const c of FLAG_CODES) codes[c] += (L.flags.rows[c] || []).length; }
  const t = stats.totals; assert.equal(t.units_with_file, 41); assert.equal(t.lines, lines); assert.equal(t.gz_bytes, gz); assert.equal(t.ocr_uncertain, unc);
  assert.equal(t.on_rolls_yes, yes); assert.equal(t.on_rolls_no, no); assert.equal(t.on_rolls_unknown, lines - yes - no); assert.equal(t.names_gettysburg, gett);
  for (const c of FLAG_CODES) assert.equal(t['flag_' + c], codes[c]);
});

test('conf-nc: no row of a unit file carries a label of presence or an extra field (marks live in the flag files)', () => {
  for (const u of UNITS) for (const x of loadUnit(u).lines.filter(Array.isArray)) assert.ok(x.length <= 5);
});

test('conf-nc: every unit file has a primary text of Moore and the second scan is used for reconciliation only', () => {
  const prim = {}; for (const u of UNITS) { const t = u.text_ids[0]; prim[t] = (prim[t] || 0) + 1; }
  const n = Object.values(prim).reduce((a, b) => a + b, 0); assert.equal(n, 41);
  for (const t of Object.keys(prim)) assert.ok(t in moore.texts, t);
  for (const u of UNITS) assert.equal(stats.units[u.unit].primary_text, u.text_ids[0]);
});
