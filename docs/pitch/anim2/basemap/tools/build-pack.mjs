// tools/build-pack.mjs - the data-URI form of the tiles, for a host page that must be ONE file (the Battle Studio is): an ES module with a named export PACK,
// { aerial: { 'z/x_y': 'data:image/avif;base64,...' }, shade: { ... } }, which the Studio's bundler can inline like any other module.
//   node tools/build-pack.mjs [--out=<file>] [--max-zoom=17]       default out: dist/pack.mjs (git-ignored)  (about 12 MB of text for the full set; not committed)
//   then:  configureBackdrop({ manifest: MANIFEST, vectors: VECTORS, pack: PACK })
// A smaller pack: --max-zoom=15 keeps z13..z15 only (about 4 MB of text), the loader then stretches z15 at higher zoom (softer, nothing missing).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BASE = path.resolve(HERE, '..');
const REPO = path.resolve(BASE, '..', '..', '..', '..');
const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith('--' + k + '=')); return a ? a.split('=')[1] : d; };
const out = arg('out', path.join(BASE, 'dist', 'pack.mjs'));
const maxZoom = +arg('max-zoom', 99);
const manifest = JSON.parse(fs.readFileSync(path.join(BASE, 'assets', 'manifest.json'), 'utf8'));
const pack = {}; let bytes = 0; let n = 0;
for (const layer of Object.keys(manifest.layers)) {
  pack[layer] = {};
  const ext = manifest.layers[layer].ext;
  for (const z of Object.keys(manifest.layers[layer].levels)) {
    if (+z > maxZoom) continue;
    const dir = path.join(BASE, 'assets', layer, z);
    for (const f of fs.readdirSync(dir)) {
      const buf = fs.readFileSync(path.join(dir, f)); bytes += buf.length; n++;
      pack[layer][z + '/' + f.replace('.' + ext, '')] = 'data:image/' + ext + ';base64,' + buf.toString('base64');
    }
  }
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '// generated by tools/build-pack.mjs: the tiles of assets/ as data URIs (named export)\nexport const PACK = ' + JSON.stringify(pack) + ';\n');
console.log('pack:', n, 'tiles,', (bytes / 1e6).toFixed(2), 'MB of images ->', (fs.statSync(out).size / 1e6).toFixed(2), 'MB module at', out);
