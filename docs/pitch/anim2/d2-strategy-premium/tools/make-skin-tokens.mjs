// tools/make-skin-tokens.mjs - turns design/premium.tokens.json (+ the variant override files in design/variants/) into the module the skin imports
// (studio/src/skins/premium.tokens.gen.mjs): rows [name, value, doc, { min, max, unit }] for the skin kit's compileTokens, and the variants as { label, set }.
// The JSON is the source of truth; the generated module is committed so the build needs nothing else, and a test fails when it is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url)); const ROOT = path.resolve(HERE, '..');
const SRC = path.join(ROOT, 'design', 'premium.tokens.json'); const OUT = path.join(ROOT, 'studio', 'src', 'skins', 'premium.tokens.gen.mjs');
function flatten(node, prefix, out, needDoc = true) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    const name = prefix ? prefix + '.' + k : k;
    if (v && typeof v === 'object' && '$value' in v) {
      if (needDoc && (typeof v.$description !== 'string' || v.$description.length < 6)) throw new Error('token ' + name + ' needs a $description');
      out.push([name, v.$value, v.$description || '', { ...(v.$min !== undefined ? { min: v.$min } : {}), ...(v.$max !== undefined ? { max: v.$max } : {}), ...(v.$unit ? { unit: v.$unit } : {}) }]);
    } else if (v && typeof v === 'object') flatten(v, name, out, needDoc);
  }
  return out;
}
const rows = flatten(JSON.parse(fs.readFileSync(SRC, 'utf8')), '', []);
const names = new Set(rows.map((r) => r[0]));
const variants = {}; const vdir = path.join(ROOT, 'design', 'variants');
for (const f of fs.existsSync(vdir) ? fs.readdirSync(vdir).sort() : []) {
  if (!f.endsWith('.json')) continue;
  const j = JSON.parse(fs.readFileSync(path.join(vdir, f), 'utf8')); const set = {};
  for (const [name, value] of flatten(j, '', [], false).map((r) => [r[0], r[1]])) { if (!names.has(name)) throw new Error('variant ' + f + ': unknown token ' + name); set[name] = value; }
  variants[path.basename(f, '.json')] = { label: j.$label || path.basename(f, '.json'), set };
}
const body = `// GENERATED by tools/make-skin-tokens.mjs from design/premium.tokens.json: do not edit by hand (edit the JSON, run node studio/build.mjs).\nexport const PREMIUM_TOKENS = ${JSON.stringify(rows, null, 1)};\nexport const PREMIUM_VARIANTS = ${JSON.stringify(variants, null, 1)};\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.error('premium.tokens.gen.mjs is stale'); process.exit(1); }
  console.log('premium.tokens.gen.mjs is current');
} else {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== body) fs.writeFileSync(OUT, body);
  console.log(`skin tokens: ${rows.length} tokens, ${Object.keys(variants).length} variants`);
}
